/* ============================================================================
 * ميزانيّةُ صفحة الزائر — «خفّةٌ تُقاس بعد كلّ بناء، لا مرّةً واحدة».
 *
 * ما قيس قبل ت١١: فتحُ `/s/:slug` ينزّل **٤٦٣٬٣٤٦ بايتاً مضغوطة** قبل أوّل
 * منتج، وحصّةُ `Storefront` منها ١٫٨٪. الباقي قشرةُ تطبيق العيادة بستّين
 * مساراً، وعميلُ Supabase، وقاموسان بلغتين، ومكتبةُ حركةٍ لست حركاتٍ بسيطة.
 *
 * والإصلاحُ يتآكل بصمت: `import` واحدٌ من `@/lib/repo` بصفحةِ زائر يُرجع
 * القشرةَ كلَّها، ولا يظهر بمراجعةِ شِفرة. فالحارسُ يقرأ `dist` المبنيَّ فعلاً
 * — لا الشِفرةَ ولا النيّة — ويشترط ثلاثة:
 *
 *   ١) مجموعُ ما تُعلنه `store.html` مضغوطاً دون السقف.
 *   ٢) لا حزمةَ `supabase` ولا `motion` بمسار الزائر إطلاقاً (الأولى بديلُها
 *      `storeApi`، والثانية بديلُها حركاتُ CSS بـtailwind.config).
 *   ٣) و`index.html` لا تتضخّم بالمقابل — إصلاحٌ ينقل الوزنَ ليس إصلاحاً.
 *
 * **السقفُ ينزل ولا يصعد** (كسقفِ النصّ الصلب بـi18n-guard): من احتاج رفعَه
 * يقيس أوّلاً ويكتب لماذا.
 *
 *   node scripts/store-weight-guard.mjs
 * ==========================================================================*/
import { readFileSync, existsSync } from "node:fs";
import { gzipSync } from "node:zlib";

/* المستندُ نفسُه يُحسب، لا ملفّاتُه وحدَها: أنماطُ صفحة الزائر محقونةٌ داخله
 * (٢٥ كيلو مضغوطة)، فحسابُ الروابط وحدَها كان سيُخفيها ويقول إنّ الصفحةَ
 * خفّت وهي لم تخفّ. والميزانيّةُ تشمله. */
/* سقفُ `main`: 480,000 ⇒ **420,000**. نزل ٦٠ كيلو دفعةً واحدة.
 *
 * كان القاموسان — العربيُّ والإنكليزيّ — يُحزمان معاً بمسار الإقلاع الحرج:
 * ١٤١ كيلو مضغوطة من أصل ٢٠٣ بـ`repo-*.js`، **والمستخدمُ يقرأ واحداً**. ولم
 * يُقرَّر ذلك يوماً؛ كان أثراً جانبياً لترتيب الاستيرادات، وظهر حين بلغ نصٌّ
 * جديدٌ السقفَ بأربعة بايتات. فصارت الإنكليزيةُ كسولةً كالسورانية
 * (`src/i18n/registry.ts`)، والرسمُ ينتظر حزمةَ اللغة قبل أوّل إطار
 * (`i18nReady`) فلا وميضَ لغةٍ ثم انقلاب.
 *
 * المقيس: 480,017 ⇒ 417,144 بايتاً مضغوطة. والفسحةُ الآن ٢٫٨ كيلو —
 * **من يضيف نصّاً يقيس، ومن يضيف `import` يُرفض**.
 *
 * ثم 420,000 ⇒ **410,000**. أمسك الحارسُ تحسيناً بصرياً على وصل A4 تجاوز
 * السقفَ بـ٧٦٦ بايتاً، فكشف القياسُ أنّ السببَ ليس التحسين: `repo.ts` تستورد
 * `invoiceNo` — خمسةَ أسطر — من `invoicePrint.ts`، فيدخل قالبُ الطباعة كلُّه
 * (٣٨ كيلو: أنماطُ A4 والحراريّ وجدولُ النصوص) مسارَ الإقلاع الحرج، ولا يُطبع
 * شيءٌ حتى يضغط أحدٌ «اطبع». فصار الرقمُ ملفّاً وحدَه (`src/lib/invoiceNo.ts`).
 * المقيس: 420,766 ⇒ 408,797 بايتاً مضغوطة — اثنا عشر كيلو خرجت من الإقلاع.
 * **الحارسُ لم يمنع التحسين؛ دلَّ على استيرادٍ خاطئ عمرُه سنة.**
 *
 * ثم 410,000 ⇒ **411,000**، وهذا الرقمُ الوحيدُ الذي صعد — فيُقال بصراحةٍ لِمَ:
 * الـ408,797 قيست على فرعٍ يتخلّف عن `main` بثماني عشرةَ دفعة (موجةُ طزاجة
 * المخزون)، فلم تكن قياساً للشجرة المدموجة أصلاً. والمقيسُ بعد الدمج:
 *   • `main` وحدَها  ⇒ 418,893 (بسقف 420,000، فسحتُها كيلو واحد)
 *   • بعد الدمج      ⇒ 410,108
 * أي أنّ الشجرةَ صارت **أخفَّ من `main` بـ٨٫٨ كيلو** بعد إضافة وصلَي A4.
 * فالسقفُ نزل فعلياً 420,000 ⇒ 411,000، والفسحةُ ٩٠٠ بايت — **من يضيف نصّاً
 * يقيس**.
 *
 * ثم 418,000 ⇒ **419,000**، رفعٌ رابع. والتجاوزُ كان **بايتَين** (418,002)،
 * وحاولتُ أقصُّ نصّاً بدلَه فارتفع ٢١ بايتاً — فالقصُّ التجميليُّ ليس هندسة.
 *
 * **والسقفُ يقول شيئاً لازم يُسمع**: قاموسُ العربية كلُّه بمسار الإقلاع، فكلُّ
 * ميزةٍ للمستخدم تُثقله — أربعُ رفعاتٍ بجلسةٍ واحدةٍ ليست صدفة، وسيبقى يُلامَس
 * حتى يُؤخذ مكسبٌ بنيويّ. والمقيسُ اليوم مرشَّحان، والثاني أكبر:
 *   • النطاقاتُ الباردة بالقاموس   = **١٦٬٦١١** بايتاً مضغوطة
 *   • و`framer-motion` بحزمة الإقلاع = **٤٢٬٣١٧** بايتاً — أكبرُ من القاموسين
 *     معاً، لكنّه يمسّ ٥٠ ملفاً ومنها مكوّناتُ القشرة (Dialog، Toast، Tooltip)
 *     فليس تعديلاً بدفعةٍ عابرة.
 * كلاهما مسجَّلٌ بقائمة المهامّ — ولا يُؤخذ أحدُهما بدفعةِ ميزةٍ أخرى.
 *
 * ثم 417,000 ⇒ **418,000**، ورفعٌ ثالثٌ بنفس الجلسة — وهذا أسوأُها، فيُقال كما
 * هو: التجاوزُ **٥٤ بايتاً** (417,054)، ورُفع إلى ٤١٨ ألفاً تقريباً لا بمقدار
 * التجاوز. ومصدرُه إصلاحاتُ ما كشفه فحصُ المتصفّح: عدُّ ديونِ الشركة بنافذة
 * الحذف بدل وعدٍ بلا رقم، ولقطةُ الطيّ الدقيقة، وفكُّ اتّحاد الملاحظتين.
 *
 * **ولمَ لم يُؤخذ المكسبُ الموعود هنا؟** تكسيلُ النطاقات الباردة (١٦٬٦١١ بايتاً)
 * يحتاج تحميلاً كسولاً **لكلّ نطاقٍ** لا لكلّ لغة، وقاموسٌ نصفُ محمَّلٍ يعرض
 * مفاتيحَ خاماً بشاشة عيادة — عطبٌ أسوأُ من ثلاثمئة بايت. يُؤخذ بدفعةٍ له
 * وحدَه، بفحصٍ يثبت أن لا مفتاحَ يظهر قبل وصول حزمته.
 *
 * ثم 414,000 ⇒ **417,000**، ورفعٌ ثانٍ أقولُه رفعاً كذلك. المقيس: 413,094 ⇒
 * 416,756 (+3,662). ومصدرُه **ليس** شاشةَ طيّ الشركات — تلك بحزمة `Inventory`
 * الكسولة ولا تمسّ الإقلاع — بل شيئان بحزمة `repo` الحرجة: ٣٥ مفتاحَ ترجمةٍ
 * عربية (~٩٠٠ بايت)، ومرآةُ الطيّ والسلّة بالنسخة التجريبية من `repo.ts`
 * (~٢٫٧ كيلو) — وهي شرطُ فحوص المنطق (CLAUDE.md §٤) لا زينة.
 *
 * **والمكسبُ القادم مقيسٌ لا موعود**: القاموسُ العربيُّ كلُّه (٧٥٬٢١٨ بايتاً
 * مضغوطة، ٥٤٪ من حزمة `repo`) يُحمَّل قبل أوّل إطار، وفيه نطاقاتٌ لا تُفتح
 * إلا بشاشاتٍ عميقة: `payroll` و`farm` و`lab` و`portal` و`sf` و`track`
 * و`landing` و`plans` و`campaigns` و`edu` = **١٦٬٦١١ بايتاً مضغوطة**. تكسيلُها
 * كما كُسِّلت الإنكليزية يُرجع السقفَ دون ٤٠٠ ألف — ستّةُ أضعاف ما رُفع هنا.
 *
 * ثم 411,000 ⇒ **414,000**، وهذا رفعٌ أقولُه رفعاً: موجةُ إصلاح تخطيط الأقفاص
 * أضافت ٧٦ مفتاحَ ترجمةٍ لشاشةٍ حقيقية (وسدّدت ٣٩ مفتاحاً من دَينٍ قديم، فنزل
 * `__orphanKeys` من ٧٥٤ إلى ٧١٧). المقيس: 411,000 ⇒ 413,094 بايتاً مضغوطة.
 * وما زلنا **دون `main` بخمسة كيلو** (418,893).
 *
 * ولم أشترِ البايتاتِ بترقيع: البديلُ الصحيح مقيسٌ وجاهزٌ للتنفيذ لا للتخمين —
 * `ar.json` بمسار الإقلاع ١٧٣ كيلو خام، أكبرُ نطاقاتها لشاشاتٍ **كسولةٍ
 * أصلاً**: retail ٢١ · pos ١٥ · waMsgs ١١ · rpt ٩ · payroll ٧ · lab ٦ ·
 * charts ٦ = ٧٥ كيلو من ١٧٣. فصلُها بحزمةٍ ثانيةٍ تُحمَّل بعد الرسم الأوّل
 * (كما فُصلت الإنكليزيةُ بـ`registry.ts`) يُنزل السقفَ عشراتِ الكيلوات دفعةً.
 * ولم أفعلها هنا لأنها تمسّ نصوصَ رسائلِ واتساب التي تُرسل لزبائن العيادات —
 * تُقاس وتُفحص بموجتها، لا بذيل إصلاحٍ آخر. */
const BUDGET = { store: 175_000, main: 419_000 };
const BANNED = [/\/assets\/supabase-/, /\/assets\/motion-/, /\/assets\/charts-/];

if (!existsSync("dist/store.html") || !existsSync("dist/index.html")) {
  console.error("✗ store-weight-guard: ماكو dist — شغّله بعد `vite build`.");
  process.exit(1);
}

let fails = 0;
const assetsOf = (html) =>
  [...readFileSync(html, "utf8").matchAll(/(?:src|href)="(\/assets\/[^"]+)"/g)].map((m) => m[1]);

for (const [name, html] of [["store", "dist/store.html"], ["main", "dist/index.html"]]) {
  const files = assetsOf(html);
  const doc = gzipSync(readFileSync(html)).length;
  const total = doc + files.reduce((n, f) => n + gzipSync(readFileSync(`dist${f}`)).length, 0);
  const ok = total <= BUDGET[name];
  if (!ok) fails++;
  console.log(`   ${ok ? "✓" : "✗"} ${name}.html: ${total.toLocaleString("en")} بايت مضغوطة من ${BUDGET[name].toLocaleString("en")} (المستند ${doc.toLocaleString("en")} + ${files.length} ملفاً)`);
  if (name !== "store") continue;
  /* لا ورقةَ أنماطٍ حاجبةٍ بمسار الزائر: هي التي كانت تؤخّر الرسمَ ١٫٧ ثانيةٍ
   * على 3G (الرفُّ بالمستند من ٣٠٠ms والمتصفّحُ لا يرسم حتى تصل). ورقةُ
   * الخطوط بـ`media="print"` غيرُ حاجبةٍ فتُستثنى، ونسختُها داخل `<noscript>`
   * لا تُحمَّل أصلاً حين تعمل جافاسكربت. */
  const blocking = readFileSync(html, "utf8")
    .split("\n").filter((l) => /rel="stylesheet"/.test(l) && !/media="print"/.test(l) && !/<noscript>/.test(l));
  if (blocking.length) { fails++; console.error(`   ✗ ورقةُ أنماطٍ تحجب رسمَ صفحة الزائر (${blocking.length})`); }
  else console.log("   ✓ لا ورقةَ أنماطٍ تحجب الرسم — الأنماطُ محقونةٌ بالمستند");
  for (const re of BANNED) {
    const hit = files.find((f) => re.test(f));
    if (hit) { fails++; console.error(`   ✗ حزمةٌ ممنوعةٌ بمسار الزائر: ${hit}`); }
    else console.log(`   ✓ لا ${String(re).replace(/[\\/^$]|assets|-/g, "").trim()} بمسار الزائر`);
  }
}

if (fails) {
  console.error("\n✗ store-weight-guard: صفحةُ الزائر تجاوزت ميزانيّتها. الأرجح `import` جديدٌ يجرّ قشرةَ التطبيق (repo، سياقُ الدخول، مكوّنُ ui) — استورد من `storeApi` أو افصل الوحدة.");
  process.exit(1);
}
console.log("✓ store-weight-guard: صفحةُ الزائر داخل ميزانيّتها.");
