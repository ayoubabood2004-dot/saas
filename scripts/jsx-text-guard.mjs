/* ============================================================================
 * حارسُ نصِّ JSX — «— ليست شرطةً، هي سبعةُ محارف».
 *
 * المقيس: صفُّ يومٍ بلا أدوية بالطبلة كان يعرض بعمود «الطبيب المعالج»
 * النصَّ `—` حرفياً، وكذلك كلُّ خانةِ رعايةٍ فارغة. السبب أن الهروب
 * `\uXXXX` هروبٌ داخل **سلسلةٍ نصّية** لا داخل **نصِّ JSX**: فـ
 *
 *     <td>{"—"}</td>   ⇒  —      (سلسلة: يُفكّ الهروب)
 *     <td>—</td>       ⇒  — (نصُّ JSX: يُطبع كما هو)
 *
 * وهو خطأٌ صامت: تسكرِبت لا يشتكي، والمترجمُ لا يشتكي، ولا يظهر إلا بشاشةٍ
 * نادرة — فبقي بالإنتاج حتى ظهر أوّلَ ما صارت الطبلةُ تُفتح فارغة.
 *
 * فالحارسُ يمسك أيَّ هروبٍ يقع بين وسمَي JSX بلا أقواسٍ حوله.
 *
 *   node scripts/jsx-text-guard.mjs
 * ==========================================================================*/
import { execSync } from "node:child_process";
import fs from "node:fs";

const files = execSync("git ls-files --cached --others --exclude-standard 'src/**/*.tsx'",
  { encoding: "utf8" }).split("\n").filter(Boolean);

/* نصُّ JSX = ما بين `>` و`<` بلا `{` ولا `}` بينهما (فلو كان بأقواسٍ صار
 * تعبيراً، والسلسلةُ داخله تفكّ هروبَها كما ينبغي).
 *
 * و`>` و`<` محرفا مقارنةٍ وسهمٍ أيضاً، فبلا تضييقٍ يلتهم النمطُ شِفرةً بين
 * `x > y` و`a < b` ويبلّغ عنها كذباً — وحارسٌ يكذب يُعطَّل، فيسقط الغرض.
 * فالتضييق: تُنزع التعليقاتُ أوّلاً، ويُرفض ما فيه `;` أو `=` (نصُّ واجهةٍ
 * لا يحملهما، والشِفرةُ لا تخلو منهما). */
const BARE = />([^<>{}=;]*\\u[0-9a-fA-F]{4}[^<>{}=;]*)</g;
const lineOf = (src, i) => src.slice(0, i).split("\n").length;
/** التعليقاتُ تُبدَّل بمسافاتٍ بنفس الطول — فتبقى أرقامُ الأسطر صادقة. */
const stripComments = (t) => t
  .replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, " "))
  .replace(/\/\/[^\n]*/g, (m) => " ".repeat(m.length));

let bad = 0, scanned = 0;
for (const f of files) {
  const src = stripComments(fs.readFileSync(f, "utf8"));
  scanned++;
  for (const m of src.matchAll(BARE)) {
    bad++;
    console.error(`   ✗ ${f}:${lineOf(src, m.index)} — هروبٌ حرفيّ بنصّ JSX: «${m[1].trim().slice(0, 60)}»`);
  }
}

if (bad) {
  console.error(`\n✗ jsx-text-guard: ${bad} موضعاً يطبع الهروبَ كما هو.`);
  console.error('  لُفَّه بأقواس — {"\\u2014"} — أو اكتب المحرفَ نفسه.');
  process.exit(1);
}
console.log(`✓ jsx-text-guard: ${scanned} ملفاً، ولا هروبَ يوونيكود عارياً بنصّ JSX.`);
