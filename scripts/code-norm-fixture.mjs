/* مولّدُ ملف القيم — يُشغَّل مرّةً ويُحفظ ناتجُه. القيمُ تُبنى من نقاط الترميز
 * لا تُكتب بيد: محرفٌ خفيّ مكتوبٌ حرفياً بملفٍّ يمسخه محرّرٌ أو نظامُ نسخ. */
import fs from "node:fs";
const C = (...n) => n.map((x) => String.fromCharCode(x)).join("");

const AR = "٠١٢٣٤٥٦٧٨٩";      // ٠-٩
const FA = "۰۱۲۳۴۵۶۷۸۹";      // ۰-۹
const d = (s, digits) => [...s].map((ch) => (ch >= "0" && ch <= "9" ? digits[+ch] : ch)).join("");

const cases = [
  // ── الطول (مصفوفة §٥) ──
  "1", "24", "0247", "00247", "1234567", "12345678", "123456789012",
  "8680542871133", "08680542871133", "12345678901234",
  "1234567890123456789012345678", "1".repeat(45),

  // ── أرقامٌ شرقية وفارسية ──
  d("8680542871133", AR), d("8680542", FA), d("2", AR) + d("4", FA) + d("7", AR),
  "12٫34", "1٬234",                    // الفاصلتان العربيتان ٫ ٬

  // ── الخفيّ: كلُّ مدىً تحذفه normalizeCode ──
  ...[0x200b, 0x200c, 0x200d, 0x200e, 0x200f,
      0x202a, 0x202b, 0x202c, 0x202d, 0x202e,
      0x2066, 0x2067, 0x2068, 0x2069, 0xfeff].flatMap((cp) => [C(cp) + "8989", "89" + C(cp) + "89", "8989" + C(cp)]),
  C(0x200e) + d("8989", AR) + C(0x200f),         // خفيّ + شرقي معاً

  // ── المسافات: كلُّ ما يعدّه JS \s (بوستغريس \s لا يشمل NBSP ولا U+2000-200A) ──
  ...[0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x20, 0xa0, 0x1680,
      0x2000, 0x2001, 0x2002, 0x2003, 0x2004, 0x2005, 0x2006, 0x2007, 0x2008, 0x2009, 0x200a,
      0x2028, 0x2029, 0x202f, 0x205f, 0x3000].map((cp) => "89" + C(cp) + "89"),
  " 8989 ", "\t8989\t", "89" + C(0x0d, 0x0a) + "89",

  // ── حالةُ الأحرف (G10) ──
  "W90", "w90", "AbC123", "abc123", "ABC-123", "Code128Z", "ZZZ", "zzz",

  // ── فواصل ورموز ──
  "12-34-56", "12:34", "A:B-c",

  // ── حالاتٌ حدّية ──
  "", "   ", C(0x200b, 0x200e, 0xfeff), "0", "00",

  // ── أشكالُ إكسل (تُطبَّع كما هي؛ رفضُها شأنُ G8 بالدفعة ٤) ──
  "1.23457E+12", "8681234567890.0",

  // ── مسخُ التخطيط العربي (يمرّ كما هو؛ إصلاحُه G7 بالدفعة ٤) ──
  "اففحس", "ظظلاش",
];

const uniq = [...new Set(cases)];
const esc = (s) => JSON.stringify(s).replace(/[-￿]/g, (c) => "\\u" + c.charCodeAt(0).toString(16).padStart(4, "0"));
fs.writeFileSync("scripts/code-norm-fixture.json", "[\n" + uniq.map((s) => "  " + esc(s)).join(",\n") + "\n]\n", "utf8");

const back = JSON.parse(fs.readFileSync("scripts/code-norm-fixture.json", "utf8"));
console.log("cases:", back.length, "| round-trip identical:", JSON.stringify(back) === JSON.stringify(uniq));
