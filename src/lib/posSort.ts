/* ============================================================================
 * ترتيبُ منتجات شاشة البيع (0279) — صِرفٌ بلا نصوص ولا شبكة: شاشةُ البيع تستورده، والفحصُ يقيسه بسلوكه.
 *
 * طلبُ المالك (١٧/١١): «يشوف أول حسب الاسم لو الأكثر مبيعاً لو الأقل مبيعاً، ولمن يختار يضل ثابت» — للعيادة كلّها، والمبيعُ آخر ٣٠ يوماً.
 *  • الترتيبُ يسبق سقفَ الرسم (٦٠): «الأكثر مبيعاً» يعني أن الستّين الأولى هي الأكثر بيعاً، لا ستّون بالاسم ثمّ تُرتَّب.
 *  • لا يُخفي شيئاً ولا يضيف: المُرتَّبُ هو المُدخَلُ نفسُه بترتيبٍ آخر (طولٌ واحد، عناصرُ نفسُها).
 *  • المادّةُ التي لم تُبع بالمدّة صفرٌ (لا «غائبة»)، والمتعادلان بترتيب وصولهما (القائمةُ بالاسم) — الفرزُ ثابتٌ (stable) فلا يقفز
 *    شيءٌ بين رسمتين، وبلا مقارنةٍ نصّية لكلّ زوج (مئاتُ المواد تُرتَّب مرّةً حين تتغيّر القائمةُ أو الأرقام، لا بكلّ ضغطة بحث).
 *  • بلا أرقام المبيع (لم تصل بعد، أو تعذّرت) يبقى بالاسم كما وصلت القائمة — والشاشةُ تقول لماذا.
 * ========================================================================= */
import type { Product } from "@/types";

export type PosSort = "name" | "top" | "low";

export function sortForPos<T extends Pick<Product, "id">>(rows: readonly T[], sort: PosSort, sales: ReadonlyMap<string, number> | null): T[] {
  if (sort === "name" || !sales) return rows.slice();
  const dir = sort === "top" ? -1 : 1;
  const qty = new Map(rows.map((p) => [p.id, sales.get(p.id) ?? 0]));
  return rows.slice().sort((a, b) => ((qty.get(a.id) as number) - (qty.get(b.id) as number)) * dir);
}

export const isPosSort = (v: unknown): v is PosSort => v === "name" || v === "top" || v === "low";
