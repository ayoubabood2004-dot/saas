/* ============================================================================
 * عيادةُ الخادم المؤكَّدة — آخرُ ما قاله `my_workspace` (حكمُ `auth_clinic()`) لهذا الحساب.
 *
 * ختمُ الطابور (outbox.ts) يحتاج «بأيّ عيادةٍ كُتبت هذه العملية» بلحظة حفظها، والحفظُ متزامن. كان
 * يأخذ مفتاحَ العيادة المحلّيّ، و"default" فيه معنيان: «عيادتي» المؤكَّدة، و«لم يُحسم بعد» (بحثُ
 * العضوية فشل فلا يُلمس المفتاح). فعمليةٌ كتبها المشغّلُ داخلَ عيادةِ زبونٍ والمفتاحُ لم يُحسم خُتمت
 * "default"، وبعد خروجه رُفعت **بعيادته هو**؛ وعمليةُ موظّفٍ حُسم مفتاحُه بعدها انتظرت أبداً بقسم
 * «حساب ثاني» (تدقيقٌ عدائيّ ١٣/١٠). فالختمُ من هنا وحده: ما أكّده الخادمُ لهذا الحساب، أو لا شيء —
 * وعمليةٌ بلا عيادةٍ مؤكَّدة تُراجَع ولا تُرفع على ظنّ.
 *
 * تُنسى حيث يتبدّل التوجيه بيد المستخدم: الخروج، ودخولُ المشغّل عيادةً وخروجُه، وقبولُ دعوةٍ وتركُ
 * عيادة. وما يتبدّل من بعيد (انتهاءُ جلسة المشغّل، مديرٌ يزيل موظّفاً) لا يُرفع به شيءٌ لعيادةٍ
 * أخرى: الطابورُ يقارن الختمَ بعيادة الخادم قبل كلّ عملية — يتأخّر ولا ينحرف.
 * ==========================================================================*/
const KEY = "vp_server_clinic";

/** يكتبها AuthContext حين يجيب `my_workspace` — ولا تُخمَّن من غيره. */
export function rememberServerClinic(user: string, clinic: string): void {
  try { localStorage.setItem(KEY, JSON.stringify({ u: user, c: clinic })); } catch { /* */ }
}
export function forgetServerClinic(): void {
  try { localStorage.removeItem(KEY); } catch { /* */ }
}
/** العيادةُ المؤكَّدة لهذا الحساب، أو null (لم تُؤكَّد، أو أُكّدت لحسابٍ آخر). */
export function confirmedClinic(user: string): string | null {
  try {
    const v = JSON.parse(localStorage.getItem(KEY) || "null") as { u?: unknown; c?: unknown } | null;
    return v && v.u === user && typeof v.c === "string" && v.c ? v.c : null;
  } catch { return null; }
}
