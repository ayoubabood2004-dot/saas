/* ============================================================================
 * مكدّسُ النوافذ — Esc تطوي **الأعلى وحدَها**.
 *
 * ── الجذر ────────────────────────────────────────────────────────────────
 * كلُّ نسخةٍ من `Modal`/`Dialog` كانت تسجّل `document.addEventListener("keydown")`
 * بلا أن تسأل «هل أنا الأعلى؟»، والستارةُ `onClick={onClose}` مثلُها. فنافذةٌ
 * تُعرض **داخل** أخرى (منتقي منتجات الشركة داخل بنّاء فاتورة الشراء) تعني أن
 * ضغطةَ Esc واحدةً تُطلق `onClose` للاثنتين معاً.
 *
 * والنتيجةُ على أرض العيادة: فاتورةُ ثلاثين سطراً تختفي بضغطةٍ واحدة — ولا
 * مسوّدةَ ولا سؤال، لأن `useEffect([open])` يعيد `setLines([blankLine()])` عند
 * إعادة الفتح. والبضاعةُ وصلت فعلاً، فتُعاد كتابتُها من الذاكرة: إدخالٌ ناقصٌ
 * أو مزدوج، وكلاهما مال.
 *
 * ── لماذا مكدّسٌ على مستوى الوحدة لا سياقُ React ─────────────────────────
 * النوافذُ تُرسم بـ`createPortal` إلى `document.body`، ومستمعُ المفاتيح على
 * `document` — فترتيبُ DOM لا يقول شيئاً عن التعشيش. والمكدّسُ يقوله: آخرُ
 * داخلٍ أوّلُ خارج، وهو ترتيبُ الفتح نفسُه.
 *
 * والدفعُ والشيلُ يجريان بنفس `useEffect` الذي يضبط `document.body.style.overflow`
 * فالتنظيفُ مربوطٌ بدورة حياة React — لا تسرّبَ عند إغلاقٍ مفاجئ.
 * ========================================================================= */

const stack: string[] = [];

/** تُنادى عند الفتح. المعرّفُ ثابتٌ لكلّ نسخة (`useId`). */
export function pushModal(id: string): void {
  // إعادةُ الفتح بنفس المعرّف لا تُكرّره — وإلا احتاج شيلاً مرّتين فبقي عالقاً.
  const at = stack.indexOf(id);
  if (at !== -1) stack.splice(at, 1);
  stack.push(id);
}

/** تُنادى عند الإغلاق أو التفكيك. */
export function removeModal(id: string): void {
  const at = stack.indexOf(id);
  if (at !== -1) stack.splice(at, 1);
}

/**
 * هل هذه النافذةُ هي الأعلى؟ **ونافذةٌ غيرُ مسجَّلةٍ تُعدّ الأعلى** عمداً:
 * الخطأُ بجانب «تُغلق» لا «تعلق مفتوحةً بلا مخرج».
 */
export function isTopModal(id: string): boolean {
  return stack.length === 0 || stack[stack.length - 1] === id;
}

export function modalDepth(): number {
  return stack.length;
}

/** للفحص وحدَه — لا تُنادى من الواجهة. */
export function resetModalStack(): void {
  stack.length = 0;
}
