/* ============================================================================
 * مسوّدةُ سعرٍ بشاشة البيع — ما يُكتب بمحرّر السعر وكيف يُقرأ عند الحفظ.
 *
 * الجذرُ المقيس (بالمتصفّح، ١٧/١٠): محرّرُ السعر كان يفتح **والسعرُ القديم فيه**
 * والمؤشّرُ بعده، فالكتابةُ تُلحَق ولا تستبدل: سعرٌ ١٨ وكُتب ٢٥ ثم Enter ⇐ **١٬٨٢٥**.
 * وبأسعار العيادات (١٥٬٠٠٠ ويُكتب ١٢٬٠٠٠) يصير ١٥٠٠٠١٢٠٠٠. فالطبيبُ «يكتب
 * بالكيبورد وما يتعدّل» — أو يتعدّل لرقمٍ لم يكتبه. وهو عينُ درس `QtyPad`
 * («الكتابة فوق رقم موجود كانت تنتج ٢٠٣ حين أراد الطبيب ٢٠ ثم ٣»).
 *
 * فالمحرّرُ يفتح **فارغاً** والسعرُ الحاليّ ظاهرٌ باهتاً (placeholder)، والكتابةُ تبدأ
 * من الصفر. والفارغُ **ليس صفراً**: `Number("")` = 0، فمسحُ الحقل ثم النقرُ خارجه كان
 * يبيع السطرَ — أو الفاتورةَ كلَّها بمحرّر الإجمالي — مجّاناً بلا كلمة. الفارغُ «لا تغيير»،
 * ومن أراد صفراً يكتب ٠.
 *
 * مفحوصٌ بـ`scripts/price-draft-test.mjs`.
 * ==========================================================================*/

/** المسوّدةُ رقماً يُحفظ، أو `null` = لا تغيير (فارغ، أو ليس رقماً، أو سالب). */
export function readPriceDraft(draft: string): number | null {
  const s = draft.trim();
  if (s === "") return null;
  const n = Number(s);
  return Number.isFinite(n) && n >= 0 ? n : null;
}
