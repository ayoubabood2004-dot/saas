/* ============================================================================
 * تجميعُ مسحة الماسح من ضغطات الكيبورد — الحقيقة التي بُني عليها هذا الملفّ:
 *
 * الماسحُ كيبوردٌ يكتب الرمزَ بسرعة الآلة ثم Enter. والفرقُ بينه وبين إنسانٍ
 * يكتب هو **الفجوةُ بين الضغطات**: أقلُّ من عشرات الملّي ثوانٍ للآلة، ومئاتٌ
 * للإنسان. القديمُ كان يقيس الفجوة بساعة الحائط لحظةَ **معالجة** الضغطة، لا
 * لحظةَ **وقوعها** — فإذا انشغل المتصفّح بالرسم بين ضغطتين (أوّلُ رقمٍ يدخل
 * حقلَ البحث فيُصفّي ٩٢٥ مادّةً ويرسم شبكتها) بدت الضغطةُ الثانية «بطيئة»
 * فمُسح ما قبلها، ووصل الرمزُ بلا رأسه.
 *
 * مقيسٌ على الإنتاج (عيادة ابن الهيثم، ٥ أيلول ٢٠٢٦، سجلُّ طلبات الخادم):
 * كلُّ مسحةٍ فاشلة كانت ١١ أو ١٢ رقماً، وكلُّ مسحةٍ ناجحة ١٣ — ونفسُ العلبة
 * تُمسح بعد ثوانٍ فتنجح. الماسحُ سليم والبضاعةُ بالمخزن؛ الذي ضاع رقمٌ أو
 * رقمان من أوّل الدفعة.
 *
 * الدفاع على طبقتين:
 *  ١) الزمنُ زمنُ الحدث (`event.timeStamp`) لا زمنُ معالجته — فانشغالُ
 *     المتصفّح لا يظهر كفجوة.
 *  ٢) الحكمُ على **الدفعة كلّها** عند Enter لا على كلّ فجوةٍ وحدها: دفعةٌ
 *     ثلاثةُ أرباع فجواتها بسرعة الآلة دفعةُ ماسح، وإن تخلّلتها فجوةٌ أو
 *     فجوتان بطيئتان. الإنسانُ لا يكتب ثلاثةَ عشرَ رقماً وفجواتُه كلُّها
 *     دون ستّين ملّي ثانية.
 * ولا يُمسح المجمَّع إلا عند **توقّفٍ حقيقي** (ثُلث ثانية فأكثر) — وهو ما
 * يفصل «كتب ٣ ثم التقط الماسح» عن رقمٍ تأخّرت معالجتُه.
 * ==========================================================================*/

export interface ScanOptions {
  /** أقلُّ طولٍ يُعدّ رمزاً (٣ افتراضاً). */
  minLength?: number;
  /** أقصى فجوةٍ بين ضغطتين تُعدّ «بسرعة الآلة» (٦٠ ملّي ثانية افتراضاً). */
  interKeyMs?: number;
  /** فجوةٌ أطولُ من هذا توقّفٌ حقيقي يبدأ دفعةً جديدة (٣٠٠ ملّي ثانية). */
  pauseMs?: number;
  /**
   * أقصى فجوةٍ يقبلها **Tab وحدَه** (٣٥ ملّي ثانية) — وهو حدٌّ أضيقُ من
   * `interKeyMs` عمداً. انظر شرحَ الفاصلَين أدناه.
   */
  tabMaxGapMs?: number;
}

export interface ScanAssembler {
  /**
   * تُغذَّى بكل ضغطة مع زمن وقوعها. ترجع الرمزَ عند Enter **أو Tab** إن كانت
   * الدفعةُ دفعةَ ماسح، وإلا `null`. وTab من إنسانٍ يتنقّل بين الحقول لا يصحّ
   * دفعةً (فجواتُه بطيئة) فيمرّ كما كان. وبقيةُ المفاتيح غير المطبوعة تُهمَل.
   */
  feed(key: string, at: number): string | null;
  reset(): void;
}

/**
 * أهذا مفتاحٌ مطبوع؟ محرفٌ واحد، أو محرفان بلا ASCII.
 *
 * السبب: مفتاح `b` بالتخطيط العربي يُخرج `e.key = «لا»` — محرفان — وشرطُ
 * `key.length !== 1` كان يرميه، فيصل الرمزُ **ناقصَ محرفٍ وسطيّ**. و`layoutFix`
 * تعالج «لا» صراحةً لكنها لا تُعيد ما لم يصل، و`matchTruncatedCode` رقميّةُ
 * الذيل فلا تنقذ حرفاً من الوسط. أما أسماءُ مفاتيح التحكّم فكلُّها ASCII
 * («Tab»، «F1»، «Up»، «Enter») فلا يمرّ منها شيء بهذا الشرط.
 */
function isPrintableKey(key: string): boolean {
  if (key.length === 1) return true;
  if (key.length !== 2) return false;
  // **نقطتان** لا وحدتا ترميز: الإيموجي طولُه محرفان ونقطتُه واحدة (زوجُ
  // بدائل)، وليس مفتاحاً بأيّ تخطيط — فلا يدخل رمزاً. و«لا» نقطتان فتمرّ.
  if ([...key].length !== 2) return false;
  for (const ch of key) if (ch.charCodeAt(0) < 128) return false;
  return true;
}

export function createScanAssembler(opts: ScanOptions = {}): ScanAssembler {
  const { minLength = 3, interKeyMs = 60, pauseMs = 300, tabMaxGapMs = 35 } = opts;
  let buf = "";
  let gaps: number[] = [];
  /* عددُ الضغطات، لا طولُ النصّ. مفتاحٌ واحد قد يُخرج محرفَين (رباطُ «لا»)،
   * فلو قِيس الحدُّ بالمحارف لبلغ رمزٌ من ثلاثة محارفَ حدَّه بضغطتين — أي
   * بفجوةٍ واحدة — فيقبل شرطُ Tab كتابةَ إنسانٍ عربيّ بفجوةٍ سريعةٍ واحدة.
   * وهذا بابُ «ابتلاعِ Tab بحقل نصّ» الذي أُغلق بالحدّ الضيّق أصلاً. */
  let keys = 0;
  let last = Number.NEGATIVE_INFINITY;
  const reset = () => { buf = ""; gaps = []; keys = 0; };
  return {
    reset,
    feed(key, at) {
      const gap = at - last;
      last = at;
      if (key === "Enter" || key === "Tab") {
        const code = buf.trim();
        const g = gaps;
        // نصفُ الفجوات بسرعة الآلة = دفعةُ ماسح (لرمزٍ بطول باركود). الإنسانُ لا
        // يكتب ستَّ فجواتٍ من اثنتَي عشرة دون ستّين ملّي ثانية — والنصفُ المتبقّي
        // يحتمل توقّفَ متصفّحٍ بطيء عن المعالجة وهو يرسم. مقيسٌ بضغطٍ على ٣٠٠٠
        // منتج: ربعُ الفجوات كان يُسقط ٥٪ من المسحات حين تتجمّع التوقّفات.
        // والرموزُ القصيرة (رقمُ رفّ، بحثٌ من حرفين وEnter) تبقى على الرُّبع، لأن
        // ضغطتين سريعتين من إنسانٍ تكفيان لتشبه دفعةً.
        const slow = g.filter((x) => x > interKeyMs).length;
        // والقسمةُ على عددِ الضغطات كذلك: دفعةٌ من ثماني ضغطاتٍ فأكثر دفعةُ
        // باركود، ولو أخرجت بعضُ مفاتيحها محرفَين.
        const tolerated = Math.floor(g.length / (keys >= 8 ? 2 : 4));
        const isScan = code.length >= minLength && keys >= minLength && slow <= tolerated;

        // Enter مُنهٍ دائماً: يُفرغ المجمَّع سواء صحّت الدفعةُ أم لا.
        if (key === "Enter") { reset(); return isScan ? code : null; }

        /* وTab مُنهٍ **للماسح وحده** — وحدُّه أضيقُ من حدّ Enter، لسببٍ مقيس.
         *
         * ماسحاتٌ كثيرة تُضبط من المصنع على Tab بدل Enter، وكان النظامُ يهملها
         * كمفتاحٍ غير مطبوع فلا تعمل مسحةٌ واحدة بتلك العيادة. لكنّ قبولَ Tab
         * بنفس تسامُح Enter (نصفُ الفجوات بطيئةٌ مسموح) فتح باباً أسوأ من الذي
         * أغلقه: **Tab مفتاحُ تنقّلٍ بين الحقول**، فكاشيرٌ يكتب رقمَ هاتف الزبون
         * بفجواتٍ ٥٥ ملّي ثانية ثم يضغط Tab تُقرأ كتابتُه «مسحة»: يُبتلع Tab
         * فلا ينتقل التركيز، ويمرّ الرقمُ بمسار المسح كلِّه فينتهي بـ«الباركود
         * مو موجود بمخزنك» بشاشة بيعٍ مفتوحة. والأسوأ: مبلغٌ قصيرٌ يُكتب سريعاً
         * بحقل الخصم أو أجرة التوصيل قد يطابق رقمَ رفّ — والمقيسُ بالإنتاج
         * ٢٩٠ منتجاً رمزُهم من سبع خاناتٍ فأقلّ، ومنهم `1000` و`2000` و`3000`
         * وهي أشيعُ أجور التوصيل — فيهبط سطرٌ بالسلّة ويُطبع بالفاتورة.
         * وهذا بعينه صنفُ «كتابةٌ صامتة يُصدَّق ناتجُها».
         *
         * فشرطُ Tab **دفعةٌ نظيفة لا متسامحة**: كلُّ الفجوات بسرعة الآلة، بلا
         * استثناء. والماسحُ لا يخسر شيئاً — فجواتُه بعشرات الملّي ثانية كلُّها،
         * أما الإنسانُ فلا تتساوى فجواتُه ولو أسرع. ويُستثنى تكرارُ مفتاحٍ
         * واحد (auto-repeat) لأنه يولّد فجواتٍ منتظمةً سريعةً بمحرفٍ مكرَّر —
         * وهو إصبعٌ على زرّ، لا مسحة.
         *
         * وEnter يبقى على تسامُحه: ليس مفتاحَ تنقّل، وقبولُه الخاطئ لا يبتلع
         * حركةً يقصدها المستخدم. */
        if (isScan && g.length > 0 && g.every((x) => x <= tabMaxGapMs) && new Set(code).size > 1) {
          reset();
          return code;
        }
        return null;
      }
      if (!isPrintableKey(key)) return null;
      if (gap > pauseMs) reset();
      if (keys > 0) gaps.push(gap);
      buf += key;
      keys += 1;
      return null;
    },
  };
}
