/** Short, human invoice number from the row id (last 6 chars, upper). */
export function invoiceNo(id: string): string {
  const tail = id.replace(/[^a-zA-Z0-9]/g, "").slice(-6).toUpperCase();
  return `INV-${tail}`;
}
