/* ============================================================================
 * تخطيطُ الكيبورد العربي — **بيانات لا نصٌّ معروض**.
 *
 * الحروفُ هنا ليست كلاماً يُقرأ على شاشة، بل **مواضعُ مفاتيح**: كلُّ حرفٍ عربيّ
 * والمحرفُ اللاتينيّ الذي يخرج من المفتاح نفسِه بتخطيط Arabic 101. ترجمتُها
 * تكسر المعنى تماماً — كترجمة رموز `waTemplates.ts`. ولهذا يسكن الملفُّ وحده
 * ويُدرَج بـ`CONTENT_FILES` بحارس الترجمة، فيبقى سقفُ `productCodes.ts` صفراً.
 *
 * ولماذا نحتاجه: الماسحُ لوحةُ مفاتيح — يرسل مواضعَ المفاتيح، والنظامُ يترجمها
 * بلغة الإدخال الحالية. فإذا كان الكيبوردُ عربياً لحظةَ مسحِ رمزٍ فيه حروف
 * (Code128، أو رمزُ QR يحمل رابطاً) خرجت حروفٌ عربية مكانها. الأرقامُ تصلحها
 * `normalizeDigits`، والحروفُ لا يصلحها شيء.
 *
 * مقيسٌ على الإنتاج: منتجٌ باركودُه `اففحس:ظظ…` — وبعكس التخطيط يقرأ
 * `https://abiroste.com/links`. أي أنه رمزُ QR لرابطٍ مُسح والكيبوردُ عربي،
 * ولم يكن باركوداً قطّ.
 * ==========================================================================*/

/** حرفٌ عربيّ ← المحرفُ اللاتينيّ من مفتاحه نفسِه (Arabic 101). */
export const AR_LAYOUT: Record<string, string> = {
  "ض": "q", "ص": "w", "ث": "e", "ق": "r", "ف": "t", "غ": "y", "ع": "u", "ه": "i",
  "خ": "o", "ح": "p", "ج": "[", "د": "]",
  "ش": "a", "س": "s", "ي": "d", "ب": "f", "ل": "g", "ا": "h", "ت": "j", "ن": "k",
  "م": "l", "ك": ";", "ط": "'",
  "ئ": "z", "ء": "x", "ؤ": "c", "ر": "v", "ى": "n", "ة": "m",
  "و": ",", "ز": ".", "ظ": "/",
};

/** هل بالنصّ حرفٌ عربيّ؟ (لا رقمٌ عربيّ — ذاك تصلحه `normalizeDigits`.) */
export const hasArabicLetters = (s: string | null | undefined): boolean =>
  /[ء-ي]/.test(String(s ?? ""));

/** يعكس مسخَ التخطيط: يرجع النصَّ اللاتينيّ، أو "" إن لم يكن فيه عربية. */
export function layoutFix(code: string | null | undefined): string {
  const s = String(code ?? "");
  if (!hasArabicLetters(s)) return "";
  // `لا` أوّلاً: محرفان من مفتاحٍ واحد (b)، ولو عولجا مفردَين لخرج `gh`.
  let out = s.replace(/لا/g, "b");
  out = [...out].map((ch) => AR_LAYOUT[ch] ?? ch).join("");
  return out === s ? "" : out;
}

/**
 * هل هذا النصُّ **مسحةٌ ممسوخة** لا كلمةٌ عربية؟ يرجع قراءتَها اللاتينية أو "".
 *
 * الفرقُ ضروريّ لأن حقولاً تقبل الاسمَ والرمزَ معاً (صندوقُ مسح المشتريات).
 * و`layoutFix` وحدَها لا تكفي: «رويال» تُعكس إلى `v,dhg` و«مستشفيات» إلى
 * `lsjatdhj` — فتحذيرٌ على كلّ اسمٍ عربيّ ضجيجٌ يُعلَّم الناسُ تجاهلَه، وحارسٌ
 * يُتجاهَل أسوأ من لا حارس.
 *
 * فالشروطُ مجتمعةً، ومأخوذةٌ من شكل ما يصل فعلاً حين يُمسح رمزٌ والكيبوردُ عربيّ:
 *  · بلا مسافة — الأسماءُ تُكتب بمسافات، والرموزُ لا؛
 *  · ثمانيةُ محارفَ فأكثر — الكلماتُ القصيرة تُشبه كلَّ شيء؛
 *  · لا يبقى حرفٌ عربيٌّ بعد العكس (همزةٌ أو تشكيلٌ يعني كلاماً لا رمزاً)؛
 *  · والناتجُ من محارف الرموز وحدها، وفيه رقمٌ أو `/` أو `:` — أي باركودٌ أو
 *    رابط. وهذا يُخرج `lsjatdhj` ويُبقي `https://abiroste.com/links` (الحالةُ
 *    المقيسة بالإنتاج). وأرقامُ الكيبورد العربيّ تصل أرقاماً شرقيةً لا حروفاً،
 *    فتصلحها `normalizeDigits` قبل أن تصل هنا.
 */
export function looksLayoutMangled(code: string | null | undefined): string {
  const s = String(code ?? "").trim();
  if (s.length < 8 || /\s/.test(s) || !hasArabicLetters(s)) return "";
  const out = layoutFix(s);
  if (!out || hasArabicLetters(out)) return "";
  if (!/^[A-Za-z0-9\-_.:/]+$/.test(out) || !/[0-9:/]/.test(out)) return "";
  return out;
}
