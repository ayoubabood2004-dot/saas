/* ============================================================================
 * «كلُّ مسارٍ آخر» بمستند الزائر (store.html) — انتقالٌ كامل، لا حلقة.
 *
 * ── الجذر (قيس على `vite preview`: GET /store.html يتكرّر بلا نهاية) ─────────────
 * القاعدةُ كانت «انتقلْ كاملاً إلا لمسارٍ بقائمة إعادات vercel.json». والقائمةُ ليست كلَّ ما
 * يخدم هذا المستند: Vercel يخدم **الملفَّ الثابت قبل الإعادات** (لهذا لا تبتلع `/(.*)` ملفّاتِ
 * /assets)، فـ/store.html نفسُه يأتي بهذا المستند — والموجّهُ لا يطابقه، و«انتقلْ إليه كاملاً»
 * يحمّل المستندَ نفسَه، وهكذا كلَّ ٣٠ms إلى أن يُغلَق التبويب.
 *
 * فالشرطُ ليس قائمةً تُلحَق: **العنوانُ الذي حُمّل عليه المستندُ فعلاً لا يُعاد تحميلُه** — الخادمُ
 * أجابه بهذا المستند مرّةً وسيجيبه به ثانيةً. وانتقالٌ داخليٌّ (رابطٌ لـ/p/) يغيّر العنوانَ بلا
 * تحميل، فهو وحده ما يُحمَّل كاملاً؛ وإن خدمه هذا المستندُ أيضاً فالتحميلُ التالي عنوانُ إقلاعه ⇒ «/».
 * فلا يتجاوز المشيُ تحميلين مهما أُضيف من إعادات.
 * ==========================================================================*/

/** ما يخدمه هذا المستندُ بإعادات vercel.json (store.html و/api/store-og) — مرآتُها. */
export const STORE_DOC_PATH = /^\/(s\/[^/]+(\/track)?|t\/[^/]+)\/?$/;

/** وجهةُ الانتقال الكامل: `boot` = العنوانُ الذي حُمّل عليه المستند (`location.pathname` لحظةَ الإقلاع). */
export function hardNavTarget(pathname: string, rest: string, boot: string): string {
  return pathname === boot || STORE_DOC_PATH.test(pathname) ? "/" : pathname + rest;
}
