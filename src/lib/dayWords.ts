/* ============================================================================
 * dayForm — صيغةُ العدد العربية لعددٍ من الأيام أو الجرعات.
 *
 * «3 أيام» صحيحة و«14 أيام» غلط، و«2 أيام» غلطٌ أوضح: العربيةُ تقول «يومين».
 * فالنصُّ لا يُبنى بـ`${n} أيام` بل يُختار مفتاحُه بالصيغة:
 *   1 ⇒ "1"   (يوم واحد / جرعة واحدة)
 *   2 ⇒ "2"   (يومين / جرعتين)
 *   3–10 ⇒ "Few"  (أيام / جرعات — جمع القلّة)
 *   11+  ⇒ "Many" (يوماً / جرعة — التمييز المفرد)
 * والمفاتيحُ تحمل الصيغة لاحقةً (`extD1`/`extD2`/`extDFew`/`extDMany`) لا لاحقاتِ CLDR،
 * فالقاموسان متكافئان مفتاحاً بمفتاح والإنكليزيةُ تكرّر ما تحتاجه.
 * ==========================================================================*/
export type DayForm = "1" | "2" | "Few" | "Many";

export function dayForm(n: number): DayForm {
  const k = Math.abs(Math.trunc(n));
  if (k === 1) return "1";
  if (k === 2) return "2";
  if (k >= 3 && k <= 10) return "Few";
  return "Many";
}
