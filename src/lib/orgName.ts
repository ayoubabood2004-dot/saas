/**
 * اسمُ الشركة والصنف: كتابتُه، ومفتاحُ مطابقته، واللقاءُ به — **من مصدرٍ واحد**.
 *
 * كان المفتاحُ يُعرَّف بكلّ شاشة، ويُقارَن **بطرفٍ واحدٍ مطبَّع**: المخزونُ يمرّ من
 * `searchable` (همزة/ة/ى والأرقام، **وطيُّ المسافات**) والمكتوبُ من `toLowerCase`
 * وحدَه. فـ«مكتب الأمير» لا يساوي «مكتبالامير» أبداً — فكلُّ حفظٍ يُنشئ شركةً جديدة
 * بنفس الاسم، ولو اختارها الطبيبُ من القائمة بضغطة.
 *
 * ومعه ضررٌ لم يُنسب إليه: الخادمُ يقبل الصنفَ (`section_id`) إن كان **لشركة
 * الفاتورة**، والفاتورةُ صارت لشركةٍ جديدة — فيسقط الصنفُ بصمتٍ ويهبط المنتجُ
 * «بدون صنف». مقيسٌ بالإنتاج: ٦٩ نسخةً زائدة بأربع عيادات، عليها ٩٨٨ منتجاً و٥٦
 * صنفاً، واحدُها بـ٢٢ نسخة.
 *
 * القاعدة (CLAUDE.md §٣): **الطرفان من نفس الدالّة** — تطبيعُ طرفٍ واحد أسوأ من لا
 * تطبيع: يفشل بصمتٍ ويبدو أنه يعمل.
 */
import { searchable } from "@/lib/utils";

/** الاسمُ كما يُخزَّن: قصُّ الأطراف، ومسافةٌ واحدة، وتوحيدُ يونيكود (NFC). */
export function orgName(s: string): string {
  return (s ?? "").trim().replace(/\s+/g, " ").normalize("NFC");
}

/** مفتاحُ المطابقة — لا يُقارَن إلا بمفتاحٍ مثله. */
export function orgKey(s: string): string {
  return searchable(orgName(s));
}

/** يلقى الصفَّ باسمه بالمفتاح الواحد. `undefined` = لا مثيلَ له فيُنشأ. */
export function findByOrgName<T extends { name: string }>(list: readonly T[], typed: string): T | undefined {
  const key = orgKey(typed);
  if (!key) return undefined;
  return list.find((x) => orgKey(x.name) === key);
}
