import { getActiveClinicId } from "./clinics";
import { supabase } from "./supabase";

/* ============================================================================
 * «أيَّ عيادةٍ يقصد هذا المتصفّح؟» — بمعرّف الخادم، ليُقارَن بختم القراءة
 * (`clinic` من store_categories_list وlist_clinic_drugs).
 *
 * ── الجذر (١٣/١٠) ─────────────────────────────────────────────────────────
 * المفتاحُ المحلّيّ (`getActiveClinicId`) يكتبه AuthContext للكادر وحده (عيادةُ الدعوة)،
 * ولا يكتبه لصاحب العيادة أبداً: `profiles.clinic_id` فارغٌ عند المالكين التسعة كلّهم
 * (مقيسٌ بالإنتاج)، فمفتاحُ المالك "default" ومعناه «عيادتي أنا» = معرّفُ حسابه. وشاشتا
 * «أدويتي» وتصنيفات المتجر كانتا تقارنان ختمَ الخادم بالمفتاح الخامّ: معرّفُ العيادة ≠
 * "default" ⇒ `switched` لكلّ مالك — «تبدّلت العيادة — حدّث الصفحة» على كلّ صاحب عيادة،
 * وصفرُ كتابةٍ من إنسانٍ بـ«أدويتي» منذ نشرها (سجلُّ التدقيق).
 *
 * المفتاحُ نفسُه لا يُبدَّل: الطابورُ يختم عملياته بـ"default" لأجهزة المالكين (`whoNow`
 * بـoutbox.ts) ولا يرفع إلا بنفس الختم، والخبيئاتُ المحلّيّة مسمّاةٌ به — تبديلُه يحبس ما
 * ينتظر. فالترجمةُ هنا، عند المقارنة وحدها: "default" = حسابُ الجلسة.
 *
 * والحارسُ باقٍ لما وُضع له (0153): مشغّلُ المنصّة داخلٌ عيادةً (الخادمُ عيادتُها،
 * والمتصفّحُ حسابُه هو)، ولحظةُ ما قبل استقرار الجلسة — كلاهما يبقى `switched`.
 * ==========================================================================*/
export async function expectedServerClinic(): Promise<string> {
  const active = getActiveClinicId() || "default";
  if (active !== "default" || !supabase) return active;
  try {
    const { data } = await supabase.auth.getSession();
    return data.session?.user?.id ?? active;
  } catch {
    return active;
  }
}
