-- ============================================================================
-- doctorVet — 0126: الرقم التسلسلي ما يعود يتصادم — أبداً
--
-- المشكلة اليوم: العميل يسحب رقماً عشوائياً بين ١٠٠٠٠ و٩٩٩٩٩ سحبةً واحدة بلا
-- إعادة، وفوق العمود فهرسٌ فريد. يعني كل تسجيلِ حيوانٍ جديد قرعةٌ ضد ٧٠٨ أرقامٍ
-- محجوزة: احتمال الفشل اليوم ٠٫٧٩٪ — نحو ١٣ حالة تضيع من كل ألف. وكل حيوانٍ
-- ينضاف يرفع الاحتمال. عند ٤٥ ألف حيوان يفشل نصف التسجيلات.
--
-- ما نرقّع بإعادة المحاولة وحدها: الترقيع يعالج المسار الذي نعرفه اليوم، ويترك
-- أي مسارِ إدخالٍ يُكتب غداً (استيراد، تطبيق آخر، لوحة سوبابيس) يقع بنفس الحفرة.
-- الحلّ بالقاعدة: العمود يولّد رقمه بنفسه، فكل مسارٍ — قائمٍ أو قادم — آمنٌ
-- بلا ما يعرف شيئاً.
--
-- كيف نضمن اللاتصادم بلا قفلٍ ولا إعادة:
--   `nextval` ذرّيّ وما يرجّع القيمة نفسها مرّتين أبداً، ولا حتى لطلبين
--   متزامنين. ونحوّل قيمته برقمٍ أوّليّ نسبةً إلى ٩٠٠٠٠ — وضربُ عددٍ لا يشاركه
--   قاسماً في حلقةٍ حسابية **تقابلٌ تامّ**: مدخلاتٌ مختلفة ⇐ مخرجاتٌ مختلفة،
--   حتماً لا احتمالاً. فالرقم يطلع مبعثراً كأنه عشوائيّ، وهو مضمون الفرادة.
--   (٩٠٠٠٠ = 2⁴·3²·5⁴، و٣٩٢١٧ فرديّ وغير قابلٍ للقسمة على ٣ ولا ٥ ⇐ متباينان.)
--
--   يبقى احتمالٌ واحد: أن يصادف الرقمُ المولَّد أحدَ الـ٧٠٨ أرقامٍ عشوائية
--   قديمة. هذي ثابتة ومعدودة، فالحلقة تتخطّاها بسحبةٍ تالية. وبعد اليوم ما
--   ينولد ولا رقمٌ عشوائيّ جديد، فالمجموعة ما تكبر.
--
-- وبعد التسعين ألفاً: ينتقل تلقائياً لستّ خانات (١٠٠٠٠٠–٩٩٩٩٩٩) بنفس المبدأ،
-- فما يوكف السستم يوم ما تكبر. ما بالكود شيء يفترض خمس خانات.
--
-- **ولا صفّ قائم ينمسّ**: الهجرة تضبط `default` للعمود فقط. الـ٧٠٨ أرقام
-- الموجودة تبقى كما هي حرفاً بحرف، والبذرة تبدأ من الصفر وتتخطّى ما يتعارض.
--
-- تراجع:
--   alter table pets alter column serial drop default;
--   drop function if exists public.next_pet_serial();
--   drop sequence if exists public.pets_serial_seq;
-- ============================================================================

create sequence if not exists public.pets_serial_seq as bigint start with 1;

create or replace function public.next_pet_serial() returns text
language plpgsql
volatile
security definer            -- لازم: بدونها يخفي RLS أرقامَ العيادات الأخرى
set search_path = public    -- ضدّ زرع دالّةٍ بمخطّط المستخدم
as $$
declare
  v     bigint;
  cand  text;
  tries int := 0;
begin
  loop
    v := nextval('public.pets_serial_seq');

    if v <= 90000 then
      -- خمس خانات: تقابلٌ تامّ على [10000, 99999]
      cand := (10000 + ((v * 39217) % 90000))::text;
    else
      -- ستّ خانات حين يمتلئ المدى الأول: تقابلٌ تامّ على [100000, 999999]
      cand := (100000 + (((v - 90000) * 392179) % 900000))::text;
    end if;

    exit when not exists (select 1 from public.pets where serial = cand);

    -- التعارض الوحيد الممكن: رقمٌ عشوائيّ قديم. نتخطّاه بالسحبة التالية.
    tries := tries + 1;
    if tries > 500 then
      -- مستحيلٌ عملياً، لكن لو صار: رقمٌ فريدٌ حتماً خارج نمط الأرقام —
      -- تسجيلُ الحالة أهمّ من جمال رقمها، ولا يجوز أن يفشل الإدخال.
      cand := 'P' || v::text;
      exit;
    end if;
  end loop;

  return cand;
end $$;

-- الـdefault ينفَّذ بصلاحية المُدخِل، فلازم يقدر ينفّذها. ما تسرّب شيئاً:
-- ترجّع رقماً جديداً ولا تكشف صفّاً ولا عمودَ عيادةٍ أخرى.
grant execute on function public.next_pet_serial() to authenticated, anon, service_role;

alter table public.pets alter column serial set default public.next_pet_serial();

-- نقدّم البذرة فوق أعلى رقمٍ خماسيّ مستعمَل لو كان المدى مزدحماً أصلاً،
-- حتى ما تلفّ الحلقة كثيراً بأول التسجيلات. (تحسينُ سرعةٍ لا شرطُ صحّة.)
do $$
declare used int;
begin
  select count(*) into used from public.pets where serial ~ '^[0-9]{5}$';
  if used > 1000 then
    perform setval('public.pets_serial_seq', used::bigint, true);
    raise notice 'db: بذرة التسلسل تقدّمت إلى % لازدحام المدى', used;
  end if;
end $$;
