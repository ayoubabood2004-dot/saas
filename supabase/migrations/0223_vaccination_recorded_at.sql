-- ============================================================================
-- ٠٢٢٣ — متى انكتب اللقاح؟ (سجلٌّ سابق يُعرف بنفسه)
--
-- صار ملفُّ الحيوان يسجّل لقاحاتٍ **سابقة** بتواريخها (ورقٌ قديم، سستمٌ سابق) —
-- جرعةٌ معطاةٌ بيومها لكلّ تاريخ، ثم الموعدُ القادم (src/lib/backdate.ts). لكنّ
-- `vaccinations` بلا أيّ ختمٍ للإدخال منذ 0001: جرعةُ أيلول المنقولة من ورقة
-- تُرى بالملفّ كأن العيادةَ أعطتها، ولا يفرّقهما شيء. والأثرُ الوحيد للإدخال كان
-- `audit_log` — وكنسُه يحذف غيرَ المال بعد ٩٠ يوماً (purge_audit_log)، فالفرقُ يضيع.
-- مقيسٌ (٦/١٠): ١٢١٢ صفّاً، ٤٨٦ منها أقدمُ من محفّز التدقيق نفسه.
--
-- `created_at` بلا قيمةٍ للصفوف القديمة عمداً: «لا نعرف» أصدقُ من وقتِ الهجرة
-- مطبوعاً على كلّ صفّ (وهو ما يفعله `add column … default now()` بخطوةٍ واحدة).
-- فالعمودُ يُضاف فارغاً ثم يأخذ افتراضيَّه للجديد وحده. ولا ملءَ من سجلّ التدقيق:
-- تحديثُ ٧٢٦ صفّاً يطلق محفّزَ التدقيق فيكتب ٧٢٦ «تعديل لقاح» بسجلّ حركات العيادات
-- عن شيءٍ لم يفعله أحدٌ منهم.
--
-- الواجهةُ لا تعتمد عليه لتعمل: تقرؤه إن وُجد (شارة «سجل سابق»)، ولا تكتبه —
-- فترتيبُ النشر (القاعدة ثم الواجهة) لا يكسر شيئاً لو انعكس.
--
-- تراجع: alter table public.vaccinations drop column if exists created_at;
-- تُطبَّق بعد 0222. وتُعاد بلا أثرٍ ثانٍ.
-- ============================================================================

set lock_timeout = '5s';

alter table public.vaccinations add column if not exists created_at timestamptz;
alter table public.vaccinations alter column created_at set default now();

comment on column public.vaccinations.created_at is
  'متى انكتب الصفّ (0223) — فارغٌ لما قبلها. administered_at أقدمُ من يومه = سجلٌّ سابق أُدخل لاحقاً.';
