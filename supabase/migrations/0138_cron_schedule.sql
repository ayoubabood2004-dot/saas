-- ============================================================================
-- doctorVet — 0138: الجدولة تنكتب بالمستودع، لا تعيش بالقاعدة وحدها
--
-- ── الدرس الذي دفعنا ثمنه ─────────────────────────────────────────────────
-- كنسُ التدقيق مجدولٌ بـpg_cron منذ 0127، لكن الجدولة نفسها ما كانت مكتوبةً
-- بأي ملفّ: تُنشأ بيدٍ بمحرّر SQL وتعيش بجدول `cron.job` وحده. فما من مكانٍ
-- يُقرأ ليُعرف «شنو مجدولٌ عندنا؟» غير القاعدة الحيّة.
--
-- ونتيجتُها ظهرت: مهمّةٌ اسمها `doctorvet-cron-probe` بقيت تشتغل **كل دقيقة**
-- من ٣٠ آب حتى ٣١ آب — ١٤٣٩ تشغيلة. سوّيناها لسببٍ وجيه: أول محاولة جدولةٍ
-- فشلت (`schema "cron" does not exist`)، وبعد تفعيل الإضافة صار عندنا جدولٌ
-- يقول `active = true` — وهذا **لا يعني أنه يشتغل**، يعني أنه مسجَّل وحسب.
-- ومهمّةٌ مسجَّلة لا تعمل تبدو تماماً كمهمّةٍ سليمة. والكنس الحقيقي موعده
-- ٣:٢٠ فجراً، فالدليل كان يحتاج انتظار ١٩ ساعة. فصنعنا مسباراً كل دقيقة
-- ليظهر السطر خلال دقيقة — ثم نسيناه.
--
-- ضررُه ما كان بالأداء: ٨٫٥ ملي ثانية للتشغيلة، ٦ صفوف بالفهرس، وصفرُ أقفالٍ
-- منتظرة عبر ١٤٣٤ تشغيلة (الحذف ياخذ ROW EXCLUSIVE، وهو لا يتعارض مع قراءةٍ
-- ولا إضافةٍ ولا تعديل، فما عطّل بيعةً ولا استعلاماً). وما حذف صفّاً زائداً:
-- ينادي نفس الدالّة بنفس النوافذ.
--
-- ضررُه كان **بمكانٍ ما نراقبه**: كل تشغيلة تكتب سطراً بـ`cron.job_run_details`،
-- وهذا الجدول بمخطّط `cron` لا `public` — فلا `purge_audit_log` تشوفه ولا شيء
-- ينظّفه. ٢٩٦ كيلو بيومٍ واحد، أي **١٠٦ ميغا بالسنة**: أكبر من القاعدة كلها
-- اليوم (٦١ ميغا)، وخُمسُ سقف الباقة — مقابل لا شيء.
--
-- ── ما تفعله هذه الهجرة ───────────────────────────────────────────────────
-- تكتب الجدولة المقصودة صراحةً، فتصير مقروءةً بالمستودع وقابلةً لإعادة البناء
-- لو أُنشئ المشروع من جديد. و`cron.schedule` تُحدّث المهمّة ذات الاسم نفسه بدل
-- أن تكرّرها، فالهجرة تُعاد بلا أثرٍ ثانٍ.
--
-- والأمر صار برقمين صريحين `(90, 365)` بدل `(30)`: الرقم الواحد كان يترك
-- الثاني لقيمته الافتراضية — والنتيجة كانت سليمةً للمال (٣٦٥ يوماً كما أردنا)
-- لكن الحركة اليومية تُكنس بشهرٍ بدل ثلاثة. والتصريح يمنع أن يتغيّر المعنى
-- يوماً بتغيّر قيمةٍ افتراضية. كلفةُ التمديد قِيست: وسيطُ الحركة ١٤٤ سطراً
-- باليوم، أي نحو ٩ ميغا زيادة عند الاستقرار — والاحتفاظ أطول لا أقصر، فما من
-- صفٍّ يُحذف بسبب هذا التغيير.
--
-- وكنسُ `rpc_refs` (0136) ينضاف: بدونه يكبر ذلك الجدول بلا سقف. موعدُه بعد
-- كنس التدقيق بربع ساعة كي لا يتزاحما على نفس اللحظة.
--
-- ── ملاحظةٌ صادقة ────────────────────────────────────────────────────────
-- `cron.job_run_details` يبقى بلا كنسٍ حتى بعد هذا: مهمّتان باليوم تكتبان
-- سطرين، أي نحو ١٥٠ كيلو بالسنة — تاريخٌ نافع لتشخيص كنسٍ فشل، وكلفتُه لا
-- تُذكر. المشكلة كانت المعدّل لا الجدول.
--
-- تراجع:
--   select cron.unschedule('doctorvet-purge-rpc-refs');
--   select cron.schedule('doctorvet-purge-audit', '20 3 * * *',
--                        $$select public.purge_audit_log(30);$$);
-- ============================================================================

do $$
begin
  -- عنقودُ الفحص المحلّي بلا pg_cron، وكذلك أي بيئةٍ ما فُعّلت فيها الإضافة.
  -- فنتخطّى بهدوء بدل أن نُفشل الهجرة كلَّها على شيءٍ ليس من المخطّط.
  if to_regproc('cron.schedule(text,text,text)') is null then
    raise notice 'db: pg_cron مو مفعّل — تخطّينا الجدولة';
    return;
  end if;

  -- كنسُ سجلّ التدقيق: ٩٠ يوماً للحركة اليومية، و٣٦٥ لأثر المال (0129).
  perform cron.schedule('doctorvet-purge-audit', '20 3 * * *',
                        'select public.purge_audit_log(90, 365);');

  -- كنسُ مراجع النداءات (0136): نافذتها سبعة أيام — ما من إعادةِ محاولةٍ
  -- تصل بعد أسبوع، فالصفّ بعدها بلا فائدة.
  perform cron.schedule('doctorvet-purge-rpc-refs', '35 3 * * *',
                        'select public.purge_rpc_refs(7);');

  -- والمسبار يُشال إن كان لسّه موجوداً: أدّى غرضه يوم أثبت أن المُجدوِل حيّ،
  -- وصارت `system_health()` (0137) تجيب نفس السؤال بلا تشغيل أي مهمّة.
  if exists (select 1 from cron.job where jobname = 'doctorvet-cron-probe') then
    perform cron.unschedule('doctorvet-cron-probe');
    raise notice 'db: انشال مسبار الكرون';
  end if;
end $$;
