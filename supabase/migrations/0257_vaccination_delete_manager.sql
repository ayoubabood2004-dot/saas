-- ============================================================================
-- ٠٢٥٧ — حذفُ اللقاح للمدير وحده، والقاعدةُ هي التي تقولها
--
-- طلبُ المالك (٣/١١): قلمٌ بـ«حالة اللقاحات» بملفّ الحيوان يعدّل اللقاحَ أو يحذفه —
-- **ضمن صلاحيات المدير**. التعديلُ يمرّ من سياسة العيادة القائمة (`for all`، الكادرُ
-- كلُّه يكتب اللقاح أصلاً: يعطي الجرعة ويؤجّلها)، فالقلمُ للمدير بالواجهة. أمّا الحذفُ
-- ففعلٌ جديد ولا يرجع: إلى اليوم ما كان بالواجهة زرُّ حذف لقاح، لكن سياسةَ العيادة تمنحه
-- لكلّ الكادر من PostgREST مباشرةً. فلا يكفي أن تُخفيه الواجهة — «زرّ الحذف على الحساب
-- المشترك» هو ما أضاع موادَّ المخزن (0145).
--
-- سياسةٌ **مقيِّدة** للحذف: تُضاف شرطاً فوق سياسة العيادة (لا تمنح شيئاً)، وتسأل
-- `auth_role()` — المديرُ، أو صاحبُ العيادة، أو مفتاحُ المدير الحيّ (PIN)، أو المشغّلُ
-- داخل العيادة (0151). وغيرُهم: الحذفُ يمرّ على صفرِ صفوفٍ بلا خطأ (هكذا تعمل RLS على
-- DELETE) — والواجهةُ تقرأ الصفرَ خطأً مسموعاً (vaxEditApi) لا «انحذف».
--
-- وما لا يتغيّر: حذفُ الحيوان يحذف لقاحاتِه بالمفتاح الأجنبيّ (on delete cascade) —
-- إجراءاتُ المفاتيح لا تمرّ من RLS، فلا يقف حذفُ حيوانٍ مسموحٍ لصاحبه على هذه السياسة
-- (مفحوصٌ بالحزمة). والمصوّرُ مسيَّجٌ أصلاً (photographer_fence_del، 0222).
-- `(select …)` لئلا يُعاد السؤالُ لكلّ صفّ (rls-initplan).
--
-- تُعاد بلا أثرٍ ثانٍ. تراجع:
--   drop policy if exists vaccinations_delete_manager on public.vaccinations;
-- ============================================================================

drop policy if exists vaccinations_delete_manager on public.vaccinations;
create policy vaccinations_delete_manager on public.vaccinations
  as restrictive for delete to authenticated
  using ((select public.auth_role()) = 'manager');
