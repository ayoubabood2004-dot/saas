-- ٠١٥٤ — استثناءُ المخزن من وضع المدير: خيارُ عيادةٍ واحد
--
-- ── المقيس ───────────────────────────────────────────────────────────────
-- «وضع المدير» (جهازٌ مقفولٌ بواجهة الاستقبال) كان يخفي أسعارَ الشراء والأرباح
-- من المخزن، **ويترك** زرَّ «أضف منتجاً» وقلمَ التعديل وسلّةَ الحذف شغّالةً.
-- فالنتيجة نصفُ حماية: الموظّفُ لا يرى الكلفةَ لكنه يقدر يفتح نموذجَ التعديل
-- ويكتب سعرَ بيعٍ جديداً — والمقصودُ من القفل أن يبيع لا أن يسعّر.
--
-- ── المبدأ ───────────────────────────────────────────────────────────────
-- القفلُ يشمل القرارَ كلَّه: إضافةُ منتجٍ أو شركةٍ أو صنف، تعديلُها، حذفُها،
-- ودمجُ التوائم، ومولّدُ الباركود، وتبويبُ المحذوفات (استرجاعٌ = تعديل).
--
-- وعياداتٌ يشتغل بها المالكُ نفسُه من جهاز الاستقبال، فالمنعُ عندها عائقٌ لا
-- حماية. فمفتاحٌ واحد **مطفأٌ افتراضياً** يعيد للمخزن تعديلَه وأسعارَه حتى
-- والجهازُ مقفول. الافتراضُ هو السلوكُ الآمن، والاستثناءُ بقرارِ العيادة.
--
-- عمودٌ واحدٌ إضافيّ، بلا لمسِ أي صفٍّ قائم — نسخةُ الواجهة القديمة تقرأ
-- الجدولَ بـ`select *` فلا يضرّها وجودُه، وتُهمله. تُعاد بلا أثرٍ ثانٍ.
-- ============================================================================

alter table public.clinic_prefs
  add column if not exists manager_mode_stock_edit boolean not null default false;

comment on column public.clinic_prefs.manager_mode_stock_edit is
  'اختياري: يُبقي تعديلَ المخزن وأسعارَ الشراء ظاهرةً حتى بوضع المدير (جهازٌ مقفول). الافتراض false = القفل يشمل المخزن.';
