-- ============================================================================
-- ٠١٦٤ — تطبيعُ الرمز واحدٌ بالطرفين، أو ليس تطبيعاً
--
-- ── المشكلة ──────────────────────────────────────────────────────────────
-- المتصفّحُ يطبّع الرمزَ بشيء، والقاعدةُ بشيءٍ أضعف. `normalizeCode` تحذف
-- الخفيَّ كلَّه (علاماتِ الاتجاه والجيوبَ والعوازلَ وBOM) ومساحاتِ يونيكود
-- كلَّها وتترجم الفارسيةَ ۰-۹؛ و`inv_norm_code` لا تعرف من ذلك إلا مسافةَ
-- ASCII والأرقامَ العربية.
--
-- فرمزٌ مخزونٌ بعلامةِ اتجاهٍ خفية — حالةٌ حقيقيةٌ بالإنتاج: باركود يبدو «8989»
-- وأوّلُ محرفٍ فيه LRM — **يطابق بالكاشير ولا يطابق بمسار الشراء الخادميّ**.
-- فتدخل البضاعةُ باسمٍ لا برمز، أو يُنشأ منتجٌ توأمٌ برصيدٍ مقسوم. وهذا هو
-- بعينه ما تحذّر منه CLAUDE.md §٣: تطبيعُ طرفٍ واحد أسوأ من لا تطبيع — يفشل
-- بصمتٍ ويبدو أنه يعمل.
--
-- ── ما تفعله هذه الهجرة ──────────────────────────────────────────────────
-- تجعل `inv_norm_code` **مرآةَ `matchCode`** بالواجهة حرفاً بحرف:
--   ١) أرقامٌ شرقية (٠-٩) وفارسية (۰-۹) والفاصلتان ٫ ٬ → لاتينية.
--   ٢) حذفُ الخفيّ ومساحاتِ يونيكود — نفسُ المجموعة التي يحذفها JS `\s`
--      مضافاً إليها مدياتُ الاتجاه. **ولا نستعمل `\s` ببوستغريس**: صنفُه لا
--      يشمل NBSP ولا U+2000-200A، فلو تُركت لبقي الطرفان مفترقين بمسافةٍ
--      لاصقةٍ من لصقِ إكسل — وهي أشيعُ من علامة الاتجاه.
--   ٣) طيُّ A–Z وحدها (G10). و`translate` لا `lower()`: التصغيرُ عمليةٌ
--      تعتمد المحليّة، فحرفٌ تركيٌّ ينزل بجافاسكربت حرفين وببوستغريس حرفاً،
--      واختلافٌ كهذا يكسر التكافؤ بحالةٍ يستحيل تتبّعها.
--
-- ── ما لا تفعله ──────────────────────────────────────────────────────────
-- لا تكتب ولا تحذف ولا «تنظّف» رمزاً مخزوناً واحداً (الخط الأحمر ١). الدالّةُ
-- للمطابقة فقط — مُقاسٌ ومؤكَّد أن مستدعياتِها الثلاثة (`record_purchase`،
-- `update_purchase`، `inventory_tidy_uncat`) تستعملها بشروط `where` لا بكتابة.
-- وطيُّ الحالة مطابقةً فقط: `normalizeCode` بالحفظ تبقى كما هي، فالباركودُ
-- يُخزَّن كما مَسَحه الماسح ويُطبع على الملصق بحروفه.
--
-- ── لماذا التغييرُ آمنٌ على القائم ──────────────────────────────────────
-- مقيسٌ على الإنتاج قبل الكتابة: **لا فهرسَ ولا قيدَ** يستعمل `inv_norm_code`
-- (استُعلم `pg_index` و`pg_constraint`) — فلا إعادةَ فهرسةٍ مطلوبة، ولا فهرسَ
-- يفسد بتبدّل دالّةٍ IMMUTABLE. و**منتجان اثنان** بكل الإنتاج باركودُهما فيه
-- أحرف، و**صفرُ** حالاتِ رمزين يفرقان بالحالة وحدها — فطيُّ الحالة لا يقدر
-- أن يدمج شيئاً قائماً.
--
-- ── الفحص ────────────────────────────────────────────────────────────────
-- `scripts/code-norm-parity.mjs` يمرّر ١١٠ قيمةً ملغومة على `matchCode`
-- الحقيقية ويولّد SQL تقارن ناتجَ هذه الدالّة بها — فأيُّ تعديلٍ لاحقٍ بأحد
-- الطرفين بلا الآخر يفشّل البناء.
--
-- إضافيةٌ وتُعاد بلا أثرٍ ثانٍ. تُطبَّق بعد 0163.
-- التراجع: أعِد نصَّ 0117 كما هو (لا بيانات تتأثر).
-- ============================================================================

create or replace function public.inv_norm_code(v text)
returns text
language sql
immutable
set search_path to 'public'
as $function$
  select translate(
           translate(
             translate(coalesce(v, ''),
               -- ٠-٩ ثم ۰-۹ ثم ٫ ٬ — بالترتيب نفسه الذي تقابله السلسلة التالية.
               -- و`||` صريحٌ بين المهارب: بوستغريس لا يدمج مهربَي U& متجاورين
               -- ضمنياً كما يدمج السلاسل العادية — يرمي خطأً نحوياً. (أمسكه
               -- الفحصُ المسبق على الإنتاج قبل أن يصل ملفَّ هجرة.)
               U&'\0660\0661\0662\0663\0664\0665\0666\0667\0668\0669'
               || U&'\06F0\06F1\06F2\06F3\06F4\06F5\06F6\06F7\06F8\06F9'
               || U&'\066B\066C',
               '01234567890123456789.,'),
             -- الخفيُّ ومساحاتُ يونيكود: نفسُ ما يحذفه matchCode بالضبط.
             -- TAB LF VT FF CR SPACE NBSP OGHAM · U+2000-200A · U+200B-200F
             -- · LS PS · U+202A-202E · NNBSP MMSP · U+2066-2069 · IDSP BOM
             U&'\0009\000A\000B\000C\000D\0020\00A0\1680'
             || U&'\2000\2001\2002\2003\2004\2005\2006\2007\2008\2009\200A'
             || U&'\200B\200C\200D\200E\200F'
             || U&'\2028\2029'
             || U&'\202A\202B\202C\202D\202E'
             || U&'\202F\205F'
             || U&'\2066\2067\2068\2069'
             || U&'\3000\FEFF',
             ''),
           'ABCDEFGHIJKLMNOPQRSTUVWXYZ', 'abcdefghijklmnopqrstuvwxyz');
$function$;

comment on function public.inv_norm_code(text) is
  'تطبيعُ رمزِ المطابقة — مرآةُ matchCode بالواجهة (src/lib/utils.ts) حرفاً بحرف، '
  'يحرسها scripts/code-norm-parity.mjs. للمطابقة فقط: لا يُخزَّن ناتجُها ولا '
  'يُكتب به عمود. أيُّ تعديلٍ هنا يقابله تعديلٌ هناك، وإلا فشل البناء.';
