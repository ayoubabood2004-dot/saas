-- ============================================================================
-- ٠٢٢٥ — رقمُ الطلب على طلب التوصيل: ما تتابع بيه العيادةُ طلبَها عند الشركة
--
-- ── المشكلة ──────────────────────────────────────────────────────────────
-- شركةُ التوصيل تعطي كلَّ طلبٍ رقمَها (بوليصة/رقم شحنة)، والزبونُ يتصل
-- «وين وصل طلبي؟» والشركةُ تسأل «شنو رقم الطلب؟». والنظامُ لا يعرف غيرَ رقم
-- الفاتورة (INV-xxxxxx) — فالعيادةُ تحفظ الرقمَ بورقةٍ أو برسالة واتساب، أو لا
-- تحفظه. المقيسُ على الإنتاج (٧/١٠): ١٬٠٦٧ طلب توصيل بخمس عيادات (٧٥٤ بآخر ٣٠
-- يوماً)، و`note` مستعملةٌ بصفٍّ واحد — فلا عادةَ قائمة نرحّلها، والعمودُ يبدأ فارغاً.
--
-- ── لماذا `courier_ref` لا `order_no` ─────────────────────────────────────
-- «رقم الطلب» بالنظام اليوم يعني رقمَ الفاتورة (على الوصل والبطاقة ورسائل
-- الواتساب)، و`store_orders.order_no` رقمُ طلبِ المتجر. اسمٌ ثالث لنفس الكلمة
-- يُخلط بهما؛ فالعمودُ اسمُه ما هو: مرجعُ الطلب عند حامله.
--
-- ── المبدأ ───────────────────────────────────────────────────────────────
-- • اختياريٌّ بالكامل: يُكتب عند البيع، أو بعده (الشركةُ كثيراً ما تعطي رقمَها
--   عند الاستلام لا عند البيع) من بطاقة الطلب أو نافذة الإرسال.
-- • **لا فهرسَ فريد**: البيعُ يكتب الفاتورة ثم الطلب بنداءين، والطلبُ الفاشل
--   يُعاد من الجهاز كما هو (0180) — تكرارُ رقمٍ كان سيُفشل الإعادةَ للأبد بعد أن
--   انحفظت الفاتورة. التكرارُ يُنبَّه عليه بالشاشة ولا يُمنع.
-- • لا فهرسَ بحث: البحثُ بالمتصفّح على قائمةٍ محمَّلةٍ كاملةً (أقصاها ٦٧٤ لعيادة).
-- • تعديلُه لكلّ الكادر — سياسةُ التحديث (0159) شرطُ عيادةٍ وحده، ومحفّزُ
--   الشركات يجمّد `collected_at`/`courier_id` فقط؛ فيُكتب بنداءٍ مستقلّ لا مع
--   الإرسال (إرسالُ طلبٍ لشركة للمدير وحده، ورقمٌ محمولٌ معه يسقط بسقوطه).
-- • والسلّةُ (0157) تصوّر الصفَّ بـ`to_jsonb(old)` فيدخلها العمودُ بلا تعديل.
--
-- إضافيةٌ وتُعاد بلا أثرٍ ثانٍ. تُطبَّق بعد 0224، **قبل** الواجهة.
-- تراجع: alter table delivery_orders drop column courier_ref (الواجهةُ تحتمل غيابه).
-- ============================================================================

set lock_timeout = '5s';

alter table public.delivery_orders add column if not exists courier_ref text;

-- طولٌ معقول: أرقامُ الشحن عشرون محرفاً أو أقلّ، والحدُّ يمنع لصقَ رسالةٍ كاملة.
-- والفراغُ يُكتب NULL لا '' — الواجهةُ تطبّعه، والقيدُ يحرس من غيرها.
do $$
begin
  alter table public.delivery_orders
    add constraint delivery_orders_courier_ref_len
    check (courier_ref is null or char_length(courier_ref) between 1 and 64);
exception when duplicate_object then null;
end $$;

comment on column public.delivery_orders.courier_ref is
  'رقمُ الطلب عند حامله — بوليصةُ شركة التوصيل أو أيُّ رقمٍ تتابع بيه العيادةُ الطلب (0225). اختياريّ، يُطبَّع بـnormalizeCode، ويُبحث بالمتصفّح.';
