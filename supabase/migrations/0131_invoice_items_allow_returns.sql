-- doctorVet — 0131: السطر الراجع سالبٌ بقصد — والقيد كان يرفضه
--
-- ── العطل من الميدان ──────────────────────────────────────────────────────
-- زبون يرجّع منتجاً وياخذ غيره بنفس العملية. الكاشير يدگّ الراجع فينزل
-- بالسالب، ثم المشترى، ويدفع الزبون الفرق. عند الحفظ:
--     new row for relation "invoice_items" violates check constraint
--     "invoice_items_nonneg"
--
-- ── السبب: هجرتان تتناقضان ────────────────────────────────────────────────
-- 0051 (تقوية أمنية) أضافت قيداً يرفض أي سطرٍ غير موجب — وكان صحيحاً يومها،
-- إذ لم يكن للسالب معنى. ثم جاءت 0122 وجعلت السطر السالب **ميزةً مقصودة**
-- (الراجع داخل السلة) وكتبت له مساراً كاملاً بالقاعدة… ونسيت القيد. فبقي
-- حارسٌ من عهدٍ سابق يمنع ميزةً من عهدٍ لاحق، وبقيت الميزة مكسورةً من يوم
-- نزولها — تُكتب وتُختبر وتفشل عند أول استعمالٍ حقيقيّ.
--
-- ── العلاج: لا نُضعف الحارس، نصحّح سؤاله ─────────────────────────────────
-- الخطأ لم يكن في وجود القيد بل في أنه يسأل «هل الكمية موجبة؟» والسؤال
-- الصحيح «هل السطر متماسك؟». فالإشارة تأتي من الكمية وحدها:
--
--   * `qty <> 0` — سطرٌ بكميةٍ صفر لا معنى له، بيعاً كان أو ردّاً. (وهذا
--     أقوى من السابق: القديم كان يقبل… لا، كان يرفض الصفر أيضاً — نُبقيه.)
--   * `unit_price >= 0` و`unit_cost >= 0` — السعر لا يكون سالباً أبداً.
--     سالبيّةُ السطر تأتي من الكمية، فلو سُمح للسعر بالسلب صار للسطر طريقان
--     إلى القيمة السالبة، وضربُ سالبَين يقلب الراجع بيعاً بصمت.
--   * وشرطٌ **جديد لم يكن موجوداً**: إشارة `stock_qty` تطابق إشارة `qty`.
--     سطرٌ يبيع قطعةً ويردّ مخزوناً في آنٍ واحد تناقضٌ يفسد الجرد بهدوء،
--     وما كان القيد القديم يمسكه لأنه كان يرفض السالب من أصله.
--
-- فالمحصّلة أن الجدول صار **أشدّ** لا أرخى: يقبل الراجع الذي قُصد، ويمنع
-- تناقضاً كان يمرّ.
--
-- `not valid` كما في 0051: لا تُفحَص الصفوف القائمة فلا تمسح الهجرةُ جدولاً
-- كبيراً ولا تفشل على صفٍّ قديم — والقيد يسري على كل كتابةٍ جديدة.
--
-- تراجع: أعد قيد 0051 (`qty > 0 and … and coalesce(stock_qty,0) >= 0`).
-- ============================================================================

alter table invoice_items drop constraint if exists invoice_items_nonneg;

do $$ begin
  alter table invoice_items
    add constraint invoice_items_nonneg
    check (
      qty <> 0
      and unit_price >= 0
      and unit_cost  >= 0
      -- الخدمات بلا مخزون (null/0) تمرّ؛ وما له مخزونٌ لازم يتّجه مع الكمية
      and (stock_qty is null or stock_qty = 0 or sign(stock_qty) = sign(qty))
    ) not valid;
exception when duplicate_object then null;
end $$;
