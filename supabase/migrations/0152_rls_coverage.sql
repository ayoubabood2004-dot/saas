-- ============================================================================
-- ٠١٥٢ — الحجبُ المقصود يُقال، والتغطيةُ تُفحص لا تُفترض
--
-- ── المشكلة ──────────────────────────────────────────────────────────────
-- تدقيقٌ كاملٌ للسياسات (٨٢ جدولاً، ١٢٢ سياسة) خرج نظيفاً: لا جدولَ بلا RLS،
-- ولا سياسةَ متساهلة إلا أسعارُ الباقات وهي علنيةٌ بقصد، ولا دالّةَ مُعرِّفٍ
-- بلا `search_path`، ولا صفَّ ابنٍ عيادتُه غيرُ عيادةِ أبيه. لكن نظافةَ اليوم
-- لا تحرس غدَ اليوم، وثغرتان تبقيان مفتوحتين بالطريقة لا بالبيانات:
--
--   ١) خمسةُ جداولَ RLS عليها مفعّلٌ **بلا سياسة**. وهذا بلغة بوستغريس حجبٌ
--      كامل، وهو المقصود: `clinic_pins` (هاشُ رمز المدير) و`staff_elevations`
--      (من رُفع مؤقتاً) و`platform_sessions` (أيَّ عيادةٍ يدخل المشغّل) لا
--      يلمسها التطبيقُ إطلاقاً — دوالُّ المُعرِّف وحدها. لكن لوحةَ أمانٍ أو
--      مراجعاً لاحقاً يقرأ «RLS مفعّل بلا سياسة» فيراها عطلاً، فيسدّها بسياسةٍ
--      «مُصلِحة» تكشف هاشات الأرقام أو تسمح لموظّفٍ أن يرفع نفسه بلا رمز.
--      فالنيّةُ إن لم تُكتب بالقاعدة نفسها تُنسى، وتُصلَّح خطأً.
--
--   ٢) لا حارسَ يسأل: هل كلُّ جدولٍ محميّ؟ `db-guard` يقرأ نصَّ الهجرات فيمسك
--      سياسةً مكتوبةً بغلط، لا جدولاً نُسي بلا سياسةٍ أصلاً.
--      و`verify_rls_equivalence` (0130) تقارن بالأصل المحفوظ، والجديدُ ليس
--      بالأصل. فجدولٌ يُضاف غداً ويُنسى `enable row level security` يمرّ من
--      الحارسين معاً — مكشوفاً لكل حاملِ المفتاح العلنيّ، بلا صرخةٍ واحدة.
--      والتدقيقُ اليدويّ لا يسدّ هذا: يصير مرّةً ثم يبيَخ.
--
-- ── المبدأ ───────────────────────────────────────────────────────────────
-- الحجبُ المقصود يُعلَن بتعليقٍ على الجدول — بالقاعدة لا بوثيقةٍ جانبية، فمن
-- يفتّش الجدولَ يقرأ نيّتَه معه. والعلامةُ لاتينيةٌ ثابتة
-- `RLS-DENY-ALL-BY-DESIGN` لا عربيةٌ مشكولة: المطابقةُ على نصٍّ بالتشكيل تفشل
-- بصمتٍ وتبدو أنها تعمل — وهذا درسٌ مدفوعٌ ثمنُه هنا من قبل.
--
-- وعليها تُبنى `verify_rls_coverage()`: ترجع كلَّ جدولٍ بلا حماية، وصفراً حين
-- لا شيء. فالجداولُ الخمسةُ تختفي من نتيجتها **لأنها موثّقة** — التعليقُ ليس
-- زينةً بل جزءٌ من آلية الفحص. وتُربط بحزمة `run.sh` فأيُّ جدولٍ جديدٍ بلا
-- حماية يفشّل الفحص قبل أن يبلغ عيادةً حيّة.
--
-- ── الأثر ────────────────────────────────────────────────────────────────
-- ولا سياسةَ تُنشأ أو تُحذف أو تُعدَّل، ولا صفَّ بيانات يُمَسّ، ولا سلوكَ شاشة
-- يتغيّر. تعليقاتٌ ودالّةُ فحصٍ فقط. إضافيةٌ وتُعاد بلا أثرٍ ثانٍ.
-- تُطبَّق بعد 0151.
-- ============================================================================

-- ── ١) إعلانُ الحجب المقصود ───────────────────────────────────────────────
-- الجداولُ التي لا يلمسها التطبيقُ إطلاقاً: RLS مفعّلٌ بلا سياسةٍ عمداً، ولا
-- تُقرأ ولا تُكتب إلا من دوالِّ المُعرِّف. التعليقُ مشروطٌ بوجود الجدول لأن
-- الحزمةَ تبني مخطّطاً جزئياً لا كلَّ تاريخ الهجرات.
do $$
declare
  t record;
begin
  for t in
    select * from (values
      ('clinic_pins',
       'هاشُ رمز المدير (bcrypt). سياسةُ قراءةٍ هنا تكشفه، وسياسةُ كتابةٍ تسمح بتبديله. '
       || 'elevate_with_pin() و set_override_pin() وحدهما تلمسانه.'),
      ('staff_elevations',
       'من رُفع إلى صلاحية مدير ومتى تنتهي. سياسةُ كتابةٍ هنا تعني أن أيَّ موظّفٍ '
       || 'يرفع نفسه مديراً بلا رمز — أي سقوطُ تجاوزِ المدير كلِّه. '
       || 'elevate_with_pin() و end_elevation() و auth_role() وحدها تلمسه.'),
      ('platform_sessions',
       'أيَّ عيادةٍ يعمل بها مشغّلُ المنصّة الآن (0151). سياسةُ كتابةٍ هنا تعني أن '
       || 'أيَّ مستخدمٍ يكتب لنفسه صفَّ جلسةٍ لعيادةٍ أخرى. platform_enter() و '
       || 'platform_leave() و platform_acting_clinic() وحدها تلمسه — وكلُّها '
       || 'تشترط is_platform_admin() أوّلاً.'),
      ('store_read_hits',
       'عدّادُ قراءات المتجر العام. يُكتب من دالّة المُعرِّف عند كل فتحةِ واجهة.'),
      ('rls_policy_backup',
       'ليست بقايا: هي **الأصلُ المحفوظ** لنصوص السياسات قبل لفِّ 0128، ومصدرُ '
       || 'البرهان لـverify_rls_equivalence() — بها يُثبَت أنه ما ضاعت سياسةٌ ولا '
       || 'تغيّر شرطٌ منذ ذلك اليوم. حذفُها يُسقط القدرةَ على إثبات ذلك. لا تحذفها.')
    ) as v(tbl, why)
  loop
    if to_regclass('public.' || t.tbl) is not null then
      execute format('comment on table public.%I is %L', t.tbl,
        'RLS-DENY-ALL-BY-DESIGN — ' || t.why);
    end if;
  end loop;
end $$;

-- ── ٢) فحصُ التغطية ───────────────────────────────────────────────────────
-- سؤالٌ واحد: أيُّ جدولٍ في public بلا حماية؟ الجوابُ الصحيح صفرُ صفوف.
--
-- جدولٌ محميٌّ = RLS مفعّلٌ **و** (له سياسةٌ واحدة على الأقل **أو** تعليقٌ يعلن
-- أن الحجبَ مقصود). فنسيانُ `enable row level security` يظهر، ونسيانُ السياسة
-- يظهر، والحجبُ المقصودُ الموثَّقُ لا يظهر — وغيرُ الموثَّق يظهر حتى يُوثَّق.
create or replace function public.verify_rls_coverage()
returns table (الجدول text, العلة text)
language sql
stable
security definer
set search_path = public
as $$
  select c.relname::text,
         case
           when not c.relrowsecurity then 'RLS مطفأ — الجدول مكشوف لكل حاملِ المفتاح العلنيّ'
           else 'RLS مفعّل بلا سياسةٍ وبلا تعليقٍ يعلن أن الحجب مقصود'
         end
  from pg_class c
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public'
    and c.relkind = 'r'
    and (
      not c.relrowsecurity
      or (
        not exists (
          select 1 from pg_policies p
           where p.schemaname = 'public' and p.tablename = c.relname
        )
        -- العلامةُ لاتينيةٌ ثابتة: مطابقةُ نصٍّ عربيٍّ مشكولٍ تفشل بصمت.
        and coalesce(obj_description(c.oid, 'pg_class'), '')
              not like '%RLS-DENY-ALL-BY-DESIGN%'
      )
    )
  order by 1;
$$;

-- دالّةُ فحصٍ للبناء لا للتطبيق: لا تُمنح لأحدٍ من أدوار الواجهة. تُنادى من
-- حزمة الاختبار (بصلاحية المالك) ومن لوحة القاعدة عند المراجعة.
revoke all on function public.verify_rls_coverage() from public, anon, authenticated;

