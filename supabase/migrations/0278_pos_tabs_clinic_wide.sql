-- ٠٢٧٨ — خاناتُ شاشة البيع للعيادة كلّها، لا لصاحب الحساب وحده
--
-- بلاغُ المالك (١٧/١١): «دكتور جرّب الخانة الجديدة وثاني يوم كال اختفت». القياسُ (استعلامُ المالك على الإنتاج) حسمه: الخاناتُ
-- الثلاث كلُّها موجودة، كلٌّ بحساب صاحبها وبعيادته — لا حذفَ ولا فشلَ حفظ. وعيادةٌ واحدة فيها خانتان بالعناصر الأربعة نفسِها:
-- «وزن» بحساب الطبيب (١٤/١١) و«الوزن» بحساب العيادة (١٦/١١). الخانةُ لم تختفِ — 0258 قصرها على صاحب الحساب (قرارٌ وقتَها:
-- «لكلّ طبيبٍ خاناتُه»)، والعيادةُ تدخل بأكثر من حساب، فمن دخل بالحساب الآخر لم يرها وصنعها ثانيةً.
--
-- قرارُ المالك (١٧/١١): **مشتركةٌ للعيادة كلّها** — أيُّ حسابٍ بالعيادة يراها ويعدّلها ويحذفها. فالسياسةُ شرطُ العيادة وحدها.
-- `user_id` يبقى ختمَ من صنعها (المحفّزُ يثبّته كما كان)، وسياجُ المصوّر (0222) كما هو. وما صُنع قبلها يظهر للعيادة كلّها حالاً
-- (لا ترحيلَ صفوف) — والخانتان المكرّرتان تظهران معاً، وتُحذف إحداهما من «عدّل الخانة».
--
-- إضافيّةٌ (سياسةٌ تُستبدل) وتُعاد بلا أثرٍ ثانٍ. تُطبَّق قبل الواجهة أو معها — الواجهةُ لا تحتاجها لتعمل، ومعها تقول «خانات العيادة».
-- تراجع: drop policy pos_custom_tabs_clinic؛ ثمّ سياسةُ 0258 حرفاً (pos_custom_tabs_own: العيادةُ والمستخدم).
-- ============================================================================

drop policy if exists pos_custom_tabs_own on public.pos_custom_tabs;
drop policy if exists pos_custom_tabs_clinic on public.pos_custom_tabs;
create policy pos_custom_tabs_clinic on public.pos_custom_tabs for all to authenticated
  using (clinic_id = (select auth_clinic()))
  with check (clinic_id = (select auth_clinic()));

-- السياجُ (restrictive) لا تمسّه إعادةُ السياسة — ونداؤه ثانيةً لا يضيف شيئاً إن كان كاملاً.
select public.photographer_fence_table('pos_custom_tabs');
