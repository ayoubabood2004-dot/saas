-- ============================================================================
-- 0102 — باركود للخدمة
--
-- المنتج عنده باركود من المصنع، أما الخدمة (فحص عام، CBC، حلاقة…) فما عندها —
-- فالكاشير مضطر يتنقّل بين التصنيفات ويدوّر عليها بكل عملية بيع. والعيادات
-- الي عندها طابعة ملصقات تصنع باركوداتها بنفسها (سكشن مولد الباركود موجود
-- أصلاً) — فيكفي أن نخزّن الرمز على الخدمة، ومسحة واحدة تنزّلها بالسلة.
--
-- الرمز اختياري ونصّي: الباركود قد يبدأ بصفر (EAN-13 يفعل)، ورقمياً يضيع
-- الصفر البادئ ويصير رمزاً آخر.
--
-- التفرّد داخل العيادة فقط: عيادتان مستقلتان قد تصنعان نفس الرقم، ومنعه
-- عالمياً يخلق تصادماً بلا سبب. والفهرس جزئي (barcode is not null) حتى لا
-- تتصادم الخدمات التي بلا باركود مع بعضها.
-- ============================================================================
alter table clinic_services add column if not exists barcode text;

create unique index if not exists clinic_services_barcode_uniq
  on clinic_services(clinic_id, barcode)
  where barcode is not null;
