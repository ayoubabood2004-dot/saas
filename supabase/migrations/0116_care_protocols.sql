-- **تركيبٌ لا جرعات**: معرّفات أدويةٍ من الدليل، وبنودُ رعايةٍ بتواترها،
-- وعددُ الأيام. والجرعة تُشتقّ لحظةَ التطبيق من نافذة النوع ووزن الحيوان —
-- فتبقى نسخةٌ واحدة من الحقيقة بالدليل الدوائي، تُراجَع فيسري تصحيحُها على
-- كل بروتوكولٍ بنته العيادة دون أن تلمسه.
