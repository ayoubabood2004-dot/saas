-- ============================================================================
-- doctorVet — 0133: تاريخٌ على بنود الفواتير — حتى تُفلتَر بالقاعدة لا بالمتصفح
--
-- ── المشكلة ───────────────────────────────────────────────────────────────
-- التقارير عندها مدى تاريخٍ أصلاً، لكنه يُطبَّق **بعد** تنزيل كل صفوف العيادة:
-- `listAllInvoiceItems()` تسحب الجدول كاملاً بصفحاتٍ متتالية، ثم يرمي
-- المتصفح ما هو خارج المدى. أي أننا ندفع ثمن كل التاريخ لنقرأ شهراً.
--
-- والحساب قاسٍ: الصفحة ألف صفّ، والقاعدة بسيول والعيادة بالعراق — نحو ٢٠٠
-- ملي ثانية للذهاب والإياب، والصفحات تُطلب واحدةً بعد الأخرى:
--     ١٠ آلاف صفّ  →  ١٠ طلبات   →  ~٢ ثانية
--     ١٠٠ ألف صفّ  →  ١٠٠ طلب    →  ~٢٢ ثانية
--     مليون صفّ    →  ١٠٠٠ طلب   →  ~٤ دقائق، وذاكرةُ آيباد تنهار قبلها
-- فالجدار ليس «الملايين» بل نحو مئة ألف صفّ.
--
-- ── لماذا عمودٌ جديد ولا نصل بالفواتير ────────────────────────────────────
-- البند يرث تاريخه من فاتورته، فالوصلة ممكنة. لكن الفلترة عبر جدولٍ مضموم
-- تمنع الفهرس من خدمة الشرط مباشرةً، وتجعل كل استعلامٍ ضمّاً. وعمودٌ مختوم
-- عند البيع يجعل الشرط على الجدول نفسه، ففهرسٌ واحد (clinic_id, created_at)
-- يقفز إلى المدى المطلوب بدل مسحٍ كامل.
--
-- ── لماذا هي آمنة تماماً ──────────────────────────────────────────────────
-- إضافةُ عمودٍ لا تعدّل صفّاً قائماً ولا تحذف شيئاً. والتعبئة الرجعية تنسخ
-- تاريخ الفاتورة الأمّ إلى بنودها — أي أنها تكتب ما كان معروفاً ضمناً، ولا
-- تخترع تاريخاً. والصفوف الجديدة تختم نفسها بـ`default now()`، وهو نفس
-- لحظة إنشاء الفاتورة عملياً (يقعان بالمعاملة ذاتها).
--
-- **ولا رقم بأي تقرير يتغيّر**: نفس المدى، نفس الصفوف، نفس النتائج — يتغيّر
-- مكانُ تطبيق الفلتر لا الفلتر نفسه.
--
-- تراجع:
--   drop index if exists invoice_items_clinic_created_idx;
--   alter table invoice_items drop column if exists created_at;
-- ============================================================================

alter table invoice_items
  add column if not exists created_at timestamptz not null default now();

-- الحارس يُرفَع للتعبئة وحدها ثم يعود.
--
-- السبب دَينُ بياناتٍ قديم: قيدُ الكميّة `not valid` منذ 0051. و`not valid`
-- تعني «لا تفحص القائم»، لا «اقبله للأبد» — بوستغريس يفحص كل صفٍّ **يُعدَّل**.
-- فصفوفٌ دخلت قبل 0051 بكميّةٍ صفر عاشت بسلام سنين، حتى يمرّ عليها أوّلُ
-- `update` فيوقظ الفحص. وتعبئتُنا هي ذلك المارّ:
--     new row … violates check constraint "invoice_items_nonneg"
--
-- ولا نحذف تلك الصفوف ولا نصلحها: بياناتُ عيادةٍ سُجّلت يوماً، ومجموعُها صفر
-- فلا تفسد رقماً. تصحيحها قرارُ صاحبها لا قرارُ هجرة.
--
-- والنافذة آمنة: محرّر SQL يلفّ اللصقة بمعاملةٍ واحدة، فلو تعثّر أي شيء تراجع
-- كلُّ شيء **بما فيه الرفع** — ولا يبقى الجدول بلا حارسٍ أبداً.
alter table invoice_items drop constraint if exists invoice_items_nonneg;

-- التعبئة الرجعية: تاريخ الفاتورة الأمّ. الشرط يمنع إعادتها على صفٍّ عُبّئ
-- سلفاً، فالهجرة تبقى قابلةً لإعادة التشغيل.
--
-- على دفعات: `update` واحدٌ على جدولٍ كبير يمسك قفلاً طويلاً وينفخ سجلّ
-- الكتابة. ألفُ صفّ بالدفعة تُنهي عملها بأجزاء ثانية وتُفرج بينها.
do $$
declare n int;
begin
  loop
    with batch as (
      select ii.id, i.created_at as src
      from invoice_items ii
      join invoices i on i.id = ii.invoice_id
      where ii.created_at > i.created_at + interval '1 second'
         or ii.created_at < i.created_at - interval '1 second'
      limit 1000
    )
    update invoice_items ii
       set created_at = b.src
      from batch b
     where ii.id = b.id;

    get diagnostics n = row_count;
    exit when n = 0;
    raise notice 'db: عُبّئ تاريخ % بند', n;
  end loop;
end $$;

-- الحارس يعود كما كان — نفس نصّ 0131 حرفاً بحرف.
do $$ begin
  alter table invoice_items
    add constraint invoice_items_nonneg
    check (
      qty <> 0
      and unit_price >= 0
      and unit_cost  >= 0
      and (stock_qty is null or stock_qty = 0 or sign(stock_qty) = sign(qty))
    ) not valid;
exception when duplicate_object then null;
end $$;

-- الفهرس الذي يجعل الفلترة قفزةً لا مسحاً.
create index if not exists invoice_items_clinic_created_idx
  on invoice_items (clinic_id, created_at desc);

