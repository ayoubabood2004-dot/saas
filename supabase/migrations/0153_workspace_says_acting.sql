-- ============================================================================
-- ٠١٥٣ — `my_workspace()` تقول أيضاً: هل مشغّلُ المنصّة داخلٌ عيادةً الآن؟
--
-- ── ما حصل فعلاً (مقيسٌ على الإنتاج) ──────────────────────────────────────
-- بعد ثانيتين من دخول المشغّل عيادةً، ظهرت بجداول إعداداتها سلالةٌ ودواءٌ
-- وأحدَ عشرَ صفَّ مؤشّراتٍ حيوية — **نسخةٌ حرفية من إعدادات عيادة المشغّل
-- نفسه**، بلا أن يلمس شيئاً.
--
-- السبب: ثلاثةُ «مُرطِّبات» (السلالات، الأدوية، معدلات القراءات) فيها فرعٌ
-- قديم غرضُه هجرةُ بياناتٍ محلية إلى السحابة أوّلَ اتّصال: «إذا الجدولُ
-- السحابيّ فارغ فارفعْ ما بهذا الجهاز». وهو صحيحٌ ما دام الطرفان يقصدان
-- العيادةَ نفسها. لكنّ المتصفّح يفتح بمفتاحٍ محلّيٍّ باسم عيادةٍ، بينما
-- `auth_clinic()` بالخادم صارت عيادةً أخرى (المشغّلُ داخل) — فينقلب «ارفعْ
-- بياناتي» إلى «انسخْ بياناتي بعيادة غيري».
--
-- ── العلاج ───────────────────────────────────────────────────────────────
-- الجذرُ أن **القراءة كتبت**. فالحلُّ أن تُمنع البذرةُ إلا بيقين: أن يتّفق
-- الخادمُ والمتصفّح على العيادة، وألّا يكون المشغّلُ داخلاً. والمتصفّحُ لا
-- يعرف الثانية إلا إن قالها الخادم — فتقولها `my_workspace()` هنا.
--
-- إضافيةٌ وتُعاد بلا أثرٍ ثانٍ. تُطبَّق بعد 0152.
-- ============================================================================

create or replace function my_workspace() returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'clinic_id', auth_clinic(),
    'role',      auth_role_base(),
    'is_staff',  auth_clinic() is distinct from auth.uid(),
    -- عيادةٌ يعمل بها مشغّلُ المنصّة الآن (0151) — وإلا null. المتصفّحُ يمتنع
    -- عن أي بذرِ إعداداتٍ ما دامت غيرَ فارغة.
    'platform_acting', platform_acting_clinic()
  );
$$;
grant execute on function my_workspace() to authenticated;
