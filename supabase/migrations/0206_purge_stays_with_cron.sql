-- ============================================================================
-- ٠٢٠٦ — الكنسُ شغلُ الجدولة وحدَها: المتصفّحُ لا يمحو أثرَ العيادة
--
-- ── ما قاسته القاعدة ────────────────────────────────────────────────────
-- 0129 قرّرت تدرُّجَ احتفاظٍ مقصوداً: الضجيجُ ٩٠ يوماً، وما يمسّ مالاً أو
-- مخزوناً (`products`, `purchases`, `purchase_items`, `invoices` …) **٣٦٥
-- يوماً**. وكتبتها بـ`purge_audit_log(p_days, p_days_money)` منزوعةَ الصلاحية
-- عن `anon` و`authenticated` — للجدولة وحدها. و0138 جدولتها، وهي تعمل:
--   cron.job #1 · `20 3 * * *` · `select public.purge_audit_log(90, 365)`
--   وآخرُ ستِّ تشغيلاتٍ كلُّها `succeeded` (مقروءةٌ من `cron.job_run_details`).
--
-- **لكنّ `purge_activity_log()` القديمة (0044) بقيت كما هي**: مسطَّحةٌ بثلاثين
-- يوماً، بلا تمييزِ مال، و`grant execute … to authenticated`. و0127 تركتها
-- عمداً وكتبتها بتعليقها: «ولا نلمس purge_activity_log() القديمة: العميل
-- ينادي اسمها عند فتح صفحة السجلّ، وحذفها يكسر الصفحة».
--
-- وكان ذلك صحيحاً يومَها، وصار خطأً حين نزلت 0129: المتصفّحُ ينادي القديمة
-- **بكلّ إقلاعِ تطبيق** (`App.tsx`) وعند فتح صفحة السجلّ (`ActivityLog.tsx`)،
-- فيمحو ما أرادت 0129 حفظَه سنةً. **التدرُّجُ مهدومٌ بدالّةٍ نُسيت.**
--
-- والمقيس: أقدمُ صفٍّ بالجدول كلِّه 2026-08-04، و٥٢٣ صفّاً فقط أقدمُ من ٣٠
-- يوماً — ١٤٦ منها `products`، وكلُّها من عياداتٍ **غيرِ نشطة**. أي أن كلَّ
-- عيادةٍ يفتح موظّفُها التطبيقَ أثرُها مقصوصٌ عند الشهر. فسؤالُ المالك «منو
-- غيّر سعر هاي المادة؟» ما له جوابٌ بعد شهر — وهو بعينه السؤالُ الذي تخدمه
-- بقيّةُ هذه الموجة.
--
-- وأسوأُ من ذلك: الصلاحيةُ لـ`authenticated` كلِّه — لا للمدير وحده. فموظّفُ
-- استقبالٍ لا يحقّ له **قراءةُ** السجلّ يمحو ثلاثين يوماً منه بفتح التطبيق.
--
-- ── العلاج: نزعُ الصلاحية، لا حذفُ الدالّة ──────────────────────────────
-- الدالّةُ تبقى موجودةً بجسمها. والسببُ أن التطبيقَ **PWA**: نسخُ الجافاسكربت
-- المخزَّنة بأجهزة العيادات تبقى تناديها أياماً بعد النشر. فحذفُها يعطيها
-- `42883` ونزعُ الصلاحية يعطيها `42501` — وكلاهما يُبلع بـ`try/catch` القائم،
-- لكنّ الإبقاءَ أهدأ ولا يكسر شيئاً. **وإزالةُ النداء من الواجهة وحدَها لا
-- تكفي** لهذا السبب بعينه: الحمايةُ لازم تكون بالقاعدة.
--
-- وما من كنسٍ يُفقد: الجدولةُ تغطّي كلَّ العيادات كلَّ ليلة، وبتدرُّجٍ أصحّ.
-- وحجمُ الجدول اليوم ٣٨ ميغا من قاعدةٍ ٨٠ ميغا — والقلقُ الذي دفع 0127
-- (نصفُ جيغا بالسنة) تكفّلت به 0129 + 0138.
--
-- تراجع:  grant execute on function public.purge_activity_log() to authenticated;
-- تُطبَّق بعد 0205. وتُعاد بلا أثرٍ ثانٍ (`revoke` لا يُراكم).
-- ============================================================================

revoke execute on function public.purge_activity_log() from public, anon, authenticated;

comment on function public.purge_activity_log() is
  'كنسٌ مسطَّحٌ بثلاثين يوماً من 0044. **منزوعُ الصلاحية منذ 0206** — كان المتصفّحُ يناديه فيهدم تدرُّجَ 0129 (المالُ والمخزون ٣٦٥ يوماً). الكنسُ شغلُ الجدولة وحدَها عبر purge_audit_log(90, 365). يبقى الجسمُ قائماً لأن نسخَ PWA المخزَّنة تناديه.';
