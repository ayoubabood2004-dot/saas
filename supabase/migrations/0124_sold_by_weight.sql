-- doctorVet — 0124: البيع بالوزن (كتلة)
--
-- منتجٌ يُعلَّم «يُباع بالوزن»: سعره (sell_price) صار سعرَ الكيلو الواحد،
-- ورصيده (stock) صار بالكيلو. عند البيع يُختار وزنٌ فيُحسب السعر خطياً —
-- نصف كيلو نصفُ السعر، كيلوان ضعفان. المخزون كسريٌّ أصلاً (numeric بدقّة
-- الغرام)، والشيك-آوت يخصم `stock_qty` كسرياً، فلا حاجة لأي تغييرٍ في منطق
-- البيع أو الجرد: العمود الجديد إشارةٌ للواجهة وحدها كي تعرض منتقي الوزن.
--
-- عمودٌ منطقيّ بسيط، افتراضه false — كل المنتجات القائمة تبقى «بالقطعة» كما هي.
-- إضافيّ وقابل لإعادة التشغيل.
-- ============================================================================

alter table products add column if not exists sold_by_weight boolean not null default false;
