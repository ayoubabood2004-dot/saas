-- ============================================================================
-- 0263 — مرفقاتُ الزيارة: التحاليلُ والأشعةُ والسونار تنرفق داخل الزيارة نفسِها
--
-- الطلب (المالك، ٦/١١): «داخل الزيارة نرفق التحاليل اللي سوّيناها وصورة الأشعة» —
-- التحاليلُ مسوّاةٌ أصلاً (مختبرٌ خارجيّ، ورقة أو PDF)، والمطلوبُ إرفاقُها لا إدخالُ قيمها.
-- وخزنةُ الوسائط (`media_items`) تحفظ صورةَ الحيوان وأشعتَه وتحليلَه منذ 0001، لكن **بالحيوان
-- وحده**: لا تعرف أيَّ زيارةٍ جات منها، فالطبيبُ داخل الزيارة ما يشوفها ولا يرفق لها.
--
-- الدفاع: `media_items.visit_id` — الزيارةُ التي أُرفق لها الملفّ (اختياريّ):
--  • الملفُّ يبقى ملكَ الحيوان: يظهر بخزنته كما كان، ويظهر بزيارته أيضاً.
--  • **بلا مفتاحٍ أجنبيّ** — مثلُ `pet_prescriptions.visit_id` (0261): المرفقُ سجلٌّ طبّيٌّ يبقى
--    ولو حُذفت الزيارة، وحذفُ الحيوان يحذفه بمفتاح pet_id كما كان.
--  • والإرفاقُ والفكُّ تحديثٌ لهذا العمود وحده بسياسة العيادة القائمة (`media_items_clinic_all`):
--    بلا دالّةٍ ولا سياسةٍ جديدة، والتدقيقُ (`audit_all`) يكتبه كما يكتب كلَّ تحديث.
--
-- إضافيّةٌ: النسخةُ القديمة من الواجهة لا ترسل العمود فلا يتغيّر عليها شيء. ويُعاد بلا أثرٍ ثانٍ.
-- تراجع (الواجهةُ أوّلاً — وإلا أرسلت visit_id لعمودٍ غائب):
--   drop index if exists media_items_visit_idx;
--   alter table media_items drop column if exists visit_id;
-- ============================================================================

alter table public.media_items
  add column if not exists visit_id uuid;

-- الزيارةُ تقرأ مرفقاتِها بمعرّفها؛ وأغلبُ الخزنة بلا زيارة فالفهرسُ جزئيّ.
create index if not exists media_items_visit_idx
  on public.media_items (visit_id) where visit_id is not null;
