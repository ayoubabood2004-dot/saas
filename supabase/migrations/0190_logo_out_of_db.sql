-- ============================================================================
-- ٠١٩٠ — شعارُ العيادة يخرج من القاعدة إلى الدلو
--
-- ── تصحيحُ سجلٍّ قبل أن يكون ميزة ─────────────────────────────────────────
-- ترويسةُ 0174 تقول: «**الصورة لا تدخل جداول القاعدة أبداً**… شعار العيادة
-- خُزّن base64 داخل `clinic_prefs` فتضخّمت صفوف سجلّ التدقيق حتى ١٠٥
-- كيلوبايت للصف الواحد (نُظّف يدوياً في ٩ أيلول)».
--
-- القياسُ اليوم يقول غيرَ ذلك:
--   • `clinic_prefs`: ٤٧ صفّاً، **٧** منها `logo_url like 'data:%'`، وصفرٌ
--     منها يحمل مساراً. أكبرُها ١٠٦٬١٣٤ محرفاً، ومجموعُها ٣٠٩٬٧٨٣.
--   • `audit_log`: ١٢٣ صفّاً تحمل `data:image` = ٥٬١٣٤ كيلوبايت من ١٨ ميغا —
--     **٢٨٪ من سجلّ التدقيق كلِّه** صورُ شعاراتٍ مكرّرة.
-- التنظيفُ اليدويّ يمحو الماضي ولا يمنع الغد. **قاعدةٌ يحرسها تعليقٌ ليست
-- قاعدة**، وهذه الهجرةُ هي حارسُها.
--
-- ── من أين دخلت البايتات ─────────────────────────────────────────────────
-- من بذرة `clinic_prefs` بـ`src/lib/settings.ts`: جهازٌ فيه شعارٌ محليٌّ
-- بصيغة `data:` من قبل أن يوجد صفٌّ سحابيّ، فتُصعِده البذرةُ كما هو. البذرةُ
-- صارت تتركه محلياً وتُصعِد مساراً وحدَه، وزرُّ «انقل الشعار» بالإعدادات
-- يرفعه ملفاً **بضغطة العيادة لا بمُرطِّب** (درس 0153: كتابةٌ تلقائية عند
-- الإقلاع هي ما أنزلت ثلاثةَ عشرَ صفَّ إعداداتٍ بعيادةِ زبونٍ لا تخصّها).
--
-- ── لماذا محفّزٌ لا قيد ──────────────────────────────────────────────────
-- `check (logo_url not like 'data:%') not valid` يتخطّى الصفوفَ القائمة عند
-- الإضافة، لكنه **يُفحص على كلّ تحديثٍ لها** — فأيُّ عيادةٍ من السبع تبدّل
-- تفضيلاً آخر يفشل تحديثُها كلُّه. المحفّزُ يقارن `OLD` بـ`NEW` فيمرّ ما لم
-- يتغيّر، ويرفض بايتاتٍ **جديدة** وحدها.
--
-- والحراسةُ داخل المحفّز القائم `clinic_prefs_guard_share()` لا بمحفّزٍ ثانٍ:
-- محفّزٌ واحدٌ للجدول ترتيبُه معلوم. وهو invoker كما هو (درس 0162: السياسةُ
-- شرطُ ملكيّةٍ وحدَها، والتجميدُ بمحفّز) ويحرس `current_user='authenticated'`
-- فقط — دوالُّ المالك وترحيلاتُ المشغّل تمرّ.
--
-- **وفحصُ الشعار قبل خروج المدير**: مشاركةُ الكتالوج قرارُ مديرٍ فيرجع باكراً،
-- أما البايتاتُ فممنوعةٌ على المدير كما على الموظّف — لا أحدَ يكتبها.
--
-- ── الحزمة ───────────────────────────────────────────────────────────────
-- يُفحص بـ`_rls_try` بدور `authenticated` (الحزمةُ superuser فلا يراها
-- المحفّز أصلاً). تُعاد الهجرةُ بلا أثرٍ ثانٍ. تُطبَّق بعد 0189.
--
-- ── ترتيبُ النشر مقلوبٌ هنا عمداً: **الواجهةُ أوّلاً ثم القاعدة** ─────────
-- القاعدةُ أوّلاً لأن الهجراتِ إضافيةٌ تحتملها الواجهةُ القديمة — وهذه ليست
-- إضافية: ترفض كتابةً تفعلها الواجهةُ القديمة فعلاً (حفظُ شعارٍ `data:`)،
-- فتنزيلُها قبل الواجهة يعطي ٥٠٠ لكلّ عيادةٍ تبدّل شعارَها. والعكسُ سليم:
-- الواجهةُ الجديدة ترفع ملفاً وتحفظ مساراً، وهي لا تحتاج المحفّزَ ليعمل.
-- ============================================================================

-- ── ١) العمودُ يقول ماذا يحمل ────────────────────────────────────────────
comment on column clinic_prefs.logo_url is
  'مسارُ شعار العيادة داخل bucket «product-images» (0190) — لا بايتاتٍ هنا أبداً. سبعةُ صفوفٍ قديمة ما زالت تحمل عنواناً مضمَّناً `data:`، والواجهةُ تقرأ الصيغتين وتعرض زرَّ نقلٍ لصاحبة الصفّ.';

-- ── ٢) المحفّزُ القائم يكسب فرعَ الشعار ─────────────────────────────────
create or replace function clinic_prefs_guard_share()
returns trigger language plpgsql set search_path = public as $$
begin
  if current_user <> 'authenticated' then return new; end if;

  -- الشعارُ أوّلاً وقبل خروج المدير: البايتاتُ ممنوعةٌ على الجميع.
  -- والمقارنةُ بـ`old` تُبقي السبعةَ القديمة قابلةً للتحديث بما لا يمسّ الشعار.
  if (tg_op = 'INSERT' and new.logo_url like 'data:%')
     or (tg_op = 'UPDATE' and new.logo_url is distinct from old.logo_url
         and new.logo_url like 'data:%') then
    raise exception 'logo_bytes_in_db'
      using hint = 'الشعارُ يُرفع ملفاً ويُحفظ مسارُه — لا صورةَ داخل جدول.';
  end if;

  if coalesce(auth_role(), '') = 'manager' then return new; end if;
  if (tg_op = 'UPDATE' and new.catalog_share is distinct from old.catalog_share)
     or (tg_op = 'INSERT' and coalesce(new.catalog_share, false)) then
    raise exception 'catalog_share_frozen'
      using hint = 'مشاركةُ الكتالوج مع العيادات قرارُ المدير وحده.';
  end if;
  return new;
end $$;

comment on function clinic_prefs_guard_share() is
  'حارسُ كتابةِ clinic_prefs: مشاركةُ الكتالوج للمدير (0162)، ولا بايتاتِ شعارٍ داخل الجدول (0190).';

-- المحفّزُ نفسُه يُعاد ربطُه ليُعاد تشغيلُ الهجرة بلا أثرٍ ثانٍ.
drop trigger if exists clinic_prefs_before_write_guard on clinic_prefs;
create trigger clinic_prefs_before_write_guard
  before insert or update on clinic_prefs
  for each row execute function clinic_prefs_guard_share();
