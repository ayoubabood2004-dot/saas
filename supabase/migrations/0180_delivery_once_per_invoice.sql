-- ============================================================================
-- ٠١٨٠ — طلبُ توصيلٍ واحدٌ لكلّ فاتورة
--
-- الجذرُ المقيس — لا الذي ظننّاه أوّلاً:
--
-- ظننّا أن المولِّد إعادةُ البيعة من شاشة البيع بعد فشل التوصيل. القياسُ نفاه:
-- `reset()` يصفّر `saleRefRef`، فالبيعةُ المعادة تحمل مرجعاً جديداً و
-- `retail_checkout` يكتب **فاتورةً جديدة** — فالفهرسُ لا يمسّها. (وضررُها
-- الحقيقيّ فاتورةٌ ثانيةٌ بخصمِ مخزونٍ ثانٍ، وذاك خارجَ ما تعالجه هذه الهجرة.)
--
-- المولِّدُ الفعليّ قبولُ طلبِ المتجر: `ClinicStore.accept()` يكتب الفاتورة
-- بمرجعٍ ثابت `store-<id>`، فإن فشل ختمُ الطلب بقي «جديداً» ⇒ يُقبَل ثانيةً ⇒
-- يُرجع 0135 **نفسَ الفاتورة** ⇒ ويُنشأ لها صفُّ توصيلٍ ثانٍ. وهذا حيٌّ اليوم:
-- منذ صار `updateStoreOrder` يرمي على صفر صفوف، كلُّ ختمٍ يُردّ يترك الطلبَ
-- قابلاً لقبولٍ ثانٍ. ذمّةٌ مضاعفةٌ على شركة التوصيل ومطالبةٌ كاذبةٌ بقيمة الطلب.
--
-- ما لا تغطّيه هذه الهجرة، صراحةً: الفاتورةَ المكرّرة (مرجعان مختلفان لنفس
-- البيعة)، ولا الختمَ الفاشل نفسَه. القيدُ على «فاتورةٌ واحدة = طلبٌ واحد» فقط.
--
-- والقاعدةُ لم تكن تمنعه: `delivery_orders_invoice_idx` (0069) فهرسٌ عاديّ
-- لا فريد.
--
-- القياسُ قبل الشحن (إنتاج، ١٤ أيلول): ٤٨٨ صفّاً، كلُّها بـinvoice_id،
-- و`group by invoice_id having count(*) > 1` رجع **صفراً** — فالفهرسُ ينزل
-- بلا تنظيفٍ ولا صفٍّ يسقط.
--
-- **بمعاملةٍ واحدة عمداً.** بلا `begin/commit` يثبت الإسقاطُ ويفشل الإنشاءُ
-- على جدولٍ فيه توأمٌ سبق، فتخرج القاعدةُ بلا فهرسٍ أصلاً — لا الفريدِ ولا
-- العاديّ — والمفتاحُ الأجنبيّ `invoice_id → invoices` بلا فهرس، وإعادةُ
-- الملفّ لا تشفيه. مُجرَّبٌ على PG16: بالمعاملة تفشل نظيفاً ويبقى فهرسُ 0069
-- مكانَه. والفجوةُ بين لحظةِ القياس ولحظةِ التطبيق ليست نظرية — المولِّدُ حيّ.
--
-- والفريدُ يحلّ محلَّ العاديّ ولا يجاوره: عمودٌ واحد بنفس الترتيب، فالفريدُ
-- يخدم كلَّ ما يخدمه العاديُّ وزيادة. وقِيس أن `invoice_id` **not null**
-- بالإنتاج — فشرطٌ جزئيّ `where invoice_id is not null` لا يعني شيئاً هنا،
-- ولا يفعل غيرَ تغيير توقيعه عند db-guard كي يمرّ بجوار العاديّ. ذاك تحايلٌ
-- على حارس لا إصلاح: الصوابُ إسقاطُ المكرَّر.
--
-- والواجهةُ تُكمل النصف الثاني: `createDeliveryOrder` تلتقط 23505 **باسم هذا
-- الفهرس** وتُرجع الصفَّ القائم بدل الرمي — فتصير إعادةُ المحاولة مأمونة
-- (نفسُ درس 0135 بالبيعة). القاعدةُ أوّلاً ثمّ الواجهة.
--
-- تُعاد بلا أثرٍ ثانٍ. تُطبَّق بعد 0179.
-- ============================================================================

begin;

drop index if exists public.delivery_orders_invoice_idx;

create unique index if not exists delivery_orders_invoice_uniq on public.delivery_orders (invoice_id);

comment on index public.delivery_orders_invoice_uniq is
  'فاتورةٌ واحدة = طلبُ توصيلٍ واحد (0180). يحلّ محلّ delivery_orders_invoice_idx العاديّ. الفشلُ يرجع 23505 والواجهةُ تُرجع الصفَّ القائم.';

commit;
